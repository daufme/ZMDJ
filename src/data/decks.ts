/**
 * **缺牌替代** —— 默认牌组专用，**不是真牌**。
 *
 * 干什么用：`decks.ts` 里的默认牌组按**真牌**写（引用已实现的卡），但那些牌所属的
 * **系列可能没启用**（`系列配置` 里 启用: false，或者那个系列文件被删了）。
 * 这时用这一张顶上，保证默认牌组**仍然是 50 张、仍然能正常开局**，
 * 而不是像以前那样在 `server.ts` 的存档解析里被静默 `.filter` 掉、牌组悄悄少几张。
 *
 * 为什么做成「**五色全能的基本领土**」：
 *   · 缺的可能是领土，也可能是单位 —— 顶上领土**永远不会让法力基础垮掉**
 *     （法力不够是一局直接打不下去的唯一原因，别的都只是变弱）；
 *   · 五种势力支持都给，所以不管缺的是哪个势力的牌，顶上去都付得出费用；
 *   · 超类别【基本】→ 不受 100.2a 的同名≤3 限制，也不会跟真牌撞名字。
 *
 * ⚠ 它**不在 `其他卡` 数组里** —— 所以不会进正式卡池、不会出现在组牌界面。
 *   服务端只把它塞进「卡号→卡」的索引里，好让默认牌组存档能解析回来。
 */
export const 缺牌替代: CardDef = {
  // ⚠ 系列码用 'ZZ' —— 它**不在 系列配置 里**，所以永远不会被 装载卡池() 导入；
  //   也**保证不会跟任何真牌撞卡号**（曾经用过 '00'/'000'，结果撞上了袁夫人 00-000，
  //   把袁夫人的索引覆盖掉了 —— tsc 看不见这种撞号）。
  系列: 'ZZ', 编号: '000', 全名: '缺牌替代',
  名称: ['缺牌替代'], 修饰符: [],
  势力: null,                     // 不属于任何势力（202.1c：势力支持看右上角，与势力属性无关）
  打出费用: [{ 操作: '支付', 点数: 0 }],                    // 203.1a
  势力需求: { 符号: {} },
  超类别: ['基本'],
  类别: ['领土'],
  稀有度: '普通',   // 代牌：纯展示字段，随便给
  副类别: [],
  势力支持: { 蓝: 1, 红: 1, 绿: 1, 黑: 1, 紫: 1 },   // 五色都给，缺哪势力的牌都顶得住
  现行文字: '（默认牌组引用的某张牌所属的系列没有启用时，用它顶上 —— 保证默认牌组仍是 50 张、开局正常。）',
  // 只提供 {1}（304.8 的固有能力由引擎统一附加），**没有** ④ 抓牌那条 —— 它就是个占位
  能力: null,
};

/** 这张牌所属的系列现在是启用的吗（不在配置表里 = 没启用） */
const 已启用 = (c: CardDef): boolean => 系列配置[c.系列]?.启用 === true;

/**
 * n 张 c。**系列没启用就换成 `缺牌替代`** ——
 * 默认牌组引用的牌不在了，也不会让牌组少几张、或者带进一张卡池里没有的牌。
 */
const 重复 = (c: CardDef, n: number): CardDef[] =>
  Array.from({ length: n }, () => (已启用(c) ? c : 缺牌替代));

