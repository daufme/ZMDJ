/**
 * 这个名字是不是**登记过的关键词**？
 * ⚠ 层6 授予的写法是「名字 + 数字」拼在一起（`'射击2'`），所以尾巴上的数字要先剥掉 ——
 *   702.1b 的可变数值就是那个数字。
 */
export function 关键词基名(名称: string): string {
  return 名称.replace(/[\d*]+$/, '');
}
/** 这个关键词名字（含带数值的写法，如「射击2」）在 702 解析表里认不认 */

export function 能解析(名称: string): boolean {
  return 名称 in 关键词解析表 || 关键词基名(名称) in 关键词解析表;
}

/**
 * **直接解析关键词能力**：没有 `种类` 的条目就是关键词（判别方式），按 702 章展开。
 * 有 `种类` 的是手写的完整能力，原样返回。
 */
export function 解析能力(ab: Ability): Ability {
  if ((ab as { 种类?: string }).种类) return ab;                 // 手写的完整能力
  const k = ab as 关键词能力;
  // ⚠ 层6 授予的关键词是「名字+数字」一个字符串（'射击2'）—— 表里只有基名（'射击'），
  //   所以查表前先剥掉尾巴数字，并把那个数字当成 702.1b 的可变数值。
  const 基名 = 关键词基名(k.名称);
  const 尾巴 = k.数值 === undefined && 基名 !== k.名称 ? Number(k.名称.slice(基名.length)) : undefined;
  const 定 = 关键词解析表[k.名称] ?? 关键词解析表[基名];
  if (!定) return ab;                                            // 没登记的沿用原样（不崩）
  if (尾巴 !== undefined && Number.isFinite(尾巴)) k.数值 = 尾巴;
  // ⚠ 展开后**要保留 名称/数值** —— 引擎里的判定点要用它（例：702.7b「只可于此装备未佩带时启动」）
  return { ...定((k.数值 ?? 0) as number | Value), 名称: k.名称, ...(k.数值 !== undefined ? { 数值: k.数值 } : {}), ...(k.特征 ? { 特征: k.特征 } : {}) } as Ability;
}
/**
 * 这个实体有没有某个**关键词能力** —— 按名字查（名字由 702 章定义）。
 *
 * 名字就是名字：引擎按名字展开（射击 → 启动式能力）或挂钩（致命 → 在 704.5e 处问）。
 * 效果查规则书，不在卡牌数据里抄一遍。
 *
 * ⚠ **不要求实体在战场上**：604.5 / 604.6 说有些静止式能力在这张牌**能被打出的区域**里
 *   就生效 —— 典型例子是手牌上的「伏击」（它决定这张牌能不能于{瞬发}时机打出）。
 * 层6 的「获得关键词」也算（122.1b 的标记可以在战场上授予关键词）。
 */

/** 带数值的关键词能力（702.10 射击 N / 702.6 坚韧 N…）；没有则为 0 */
export function 关键词数值(g: GameState, o: Obj, 名: string): number {
  // ① 牌面自己印的（{ 名称:'射击', 数值:2 }）
  const abs = (o.def.能力?.能力 ?? []) as { 名称?: string; 数值?: number }[];
  const 印 = abs.find((ab) => ab.名称 === 名)?.数值;
  if (印 !== undefined) return 印;
  // ② **层 6 授予的**（「所附属的单位具有射击2」那类，见 092 箭术训练）——
  //    授予时写的是「名字 + 数字」拼在一起的一个字符串，这里把尾巴上的数字解析出来。
  if (o.区域 !== '战场') return 0;
  for (const k of 计算特征(g, o).关键词) {
    if (k.名称 === 名) return typeof k.数值 === 'number' ? k.数值 : (k.数值 !== undefined ? 层值(k.数值, o, g) : 0);
    // 层6 授予的写法是「名字 + 数字」拼在一起的一个字符串（'射击2'）
    if (k.名称.startsWith(名)) { const n = Number(k.名称.slice(名.length)); if (Number.isFinite(n)) return n; }
  }
  return 0;
}
