/**
 * **历史条件查询** —— 这个实体过去有没有发生过这件事（Selector.历史 用）。
 * 四个部件：**事件 × 角色 × 时段 × 数量**。
 */
export function 发生过(g: GameState, o: Obj, 条: 历史条件): boolean {
  return g.事件记录.some((e) =>
    e.事件 === 条.事件
    && (条.时段 === undefined || 条.时段 === '这盘游戏'
      || (条.时段 === '本回合' && e.回合 === g.turn)
      || (条.时段 === '上回合' && e.回合 === g.turn - 1)
      || (条.时段 === '本步骤' && e.回合 === g.turn && e.步骤 === g.当前步骤))
    // 角色：省略 = **这个实体在任一边**（不是「不检查实体」）
    && (条.角色 === '来源' ? e.来源 === o.uid
      : 条.角色 === '受方' ? e.受方 === o.uid
        : e.来源 === o.uid || e.受方 === o.uid)
    && (条.数量 === undefined || 数量比较(e.数量 ?? 0, 条.数量)),
  );
}
/** 数量比较（复用 筛选比较） */
function 数量比较(实际: number, c: { 比较: 筛选比较; 值: number }): boolean {
  if (c.比较 === '大于') return 实际 > c.值;
  if (c.比较 === '小于') return 实际 < c.值;
  if (c.比较 === '小于等于') return 实际 <= c.值;
  if (c.比较 === '大于等于') return 实际 >= c.值;
  return 实际 === c.值;
}

/**
 * 一个物件是否符合这个 Selector（611.3 的范围判断）。
 * 和 engine.ts 里那个「按筛选条件判断」不同 —— 这里判断的是**范围**（谁受影响），
 * 用的是**算完的特征** f（613：受前面层影响）。
 */
export function 符合选择器(g: GameState, o: Obj, sel: Selector | undefined, 锚: Obj | null, 控制器: number, f: 特征, 触发受方?: Obj | number, 记忆源?: Obj): boolean {
  if (!sel) return true;
  const 条件: 筛选 = sel.筛选 ?? [];
  /**
   * ★ **B 阶段 2**：Selector 的顶层字段**翻译成 `筛选` 条件** ✓，判定**只有一条路**（`符合筛选` ✓）。
   *   ⚠ `历史` 不是筛选属性（它查引擎的事件记录 ✓）→ 仍然单独判 ✓，不混进来 ✗。
   */
  // 历史条件  // 历史条件（「本回合受到过伤害的」…）—— 查引擎的事件记录，不属于"特征筛选" ✗
  if (sel.历史 && !sel.历史.every((c) => 发生过(g, o, c))) return false;
  return 符合筛选(g, o, 条件, f, undefined, 记忆源, 锚, 控制器, 触发受方);
}

/**
 * **层 2：改变操控权**（613.1b）—— 算出来的有效操控者。
 *
 * `o.操控者` 是**基础值**（印在牌上/永久改变），**不在原地改** ——
 * 因为这是持续性效应（611.1），来源离场就要恢复。
 *
 * 多个效应时按时间印记，**最晚的说了算**（613.7）。
 */
const 算操控权中 = new Set<number>();
/**
 * **613.1b 层 2 之后的操控者** —— 「由你操控的」一律按它算，不读 `o.操控者`。
 * 非战场物件直接返回 `o.操控者`（层系统只管战场）。
 *
 * ⚠ 内部有 `算操控权中` 递归护栏：算操控权要 计算特征 → 符合选择器 → 又可能问回操控权，
 *   同一个物件在算的过程中直接返回基础值。**别在护栏范围内调 有效控制器 去算别的物件** ——
 *   那绕不过护栏，会栈溢出（`自身加成` 就踩过这个坑）。
 */

export function 有效控制器(g: GameState, o: Obj): number {
  if (o.区域 !== '战场') return o.操控者;
  // ⚠ 递归保护：算操控权要 计算特征 → 符合选择器 → 又可能问操控权。
  //   同一个物件在算的过程中直接返回基础值（此时它就是「还没被改过」的）。
  if (算操控权中.has(o.uid)) return o.操控者;
  算操控权中.add(o.uid);
  try { return 算有效控制器(g, o); } finally { 算操控权中.delete(o.uid); }
}
function 算有效控制器(g: GameState, o: Obj): number {
  // ⚠ **只算到层 2**：改操控权是层 2 的效应，它该在「层 2 之前」的特征上匹配。
  //   以前这里调完整 计算特征，既让一次属性访问触发世界重算（递归源头），
  //   又让层 2 看到了层 4/6/7 之后的样子 —— 层序错了。
  const s = 取快照(g);
  const 有 = s.操控者.get(o.uid);
  if (有 !== undefined) return 有;                        // 同一状态版本内直接复用 ✓
  const f = 计算到层(g, o, 2);
  const 层2 = s.候选.filter((c) => c.层.操控权 !== undefined && 匹配(g, c, o, f));
  if (!层2.length) { s.操控者.set(o.uid, o.操控者); return o.操控者; }
  层2.sort((a, b) => a.时间印记 - b.时间印记);
  const 尾 = 层2[层2.length - 1]!;
  const 值 = 尾.层.操控权 === '你' ? 尾.控制器 : o.操控者;
  if (!s.构建中) s.操控者.set(o.uid, 值);
  return 值;
}

function 匹配(g: GameState, c: 候选效应, o: Obj, f: 特征, 判断?: 条件判断): boolean {
  // ⚠ 611.2b 的「只要……」**必须排在最前面** ——
  //   它在 指定 型效应上同样要判（【降服】就是指定型的），排在后面会被提前 return 掉
  if (c.条件 && !条件成立(g, o, c.条件, c.来源, 判断)) return false;
  if (c.受锁定 && !c.受锁定.includes(o.uid)) return false;   // 611.2c 锁定的物件组不再改变
  // ⚠ 派生自 `g.连续效应` 的：**按 uid 比** —— 目标已经不在场上了就**谁都不匹配**，
  //   不能因为「找不到那个实体」就退回范围匹配（那会让效应漫延，见字段说明）。
  if (c.指定uid !== undefined) return c.指定uid === o.uid;
  if (c.指定) return c.指定 === o;                           // 内部候选：直接就是那个物件
  if (!符合选择器(g, o, c.范围, c.来源, c.控制器, f)) return false;
  if (!符合筛选(g, o, c.筛选, f)) return false;
  return true;
}

export type 条件判断 = (c: unknown) => boolean;

/**
 * **611.2b「只要……」条件成立吗**。
 * 条件在结算时已经把目标**解析成 uid** 了（见 持续 操作），所以这里不需要 StackItem。
 * 内建认识 `附属在`（306.4b）；别的形状交给调用方传的 `判断` 回调。
 */
function 条件成立(g: GameState, o: Obj, 条件: unknown, 来源: Obj | null, 判断?: 条件判断): boolean {
  const c = 条件 as { 操作?: string; 目标?: string };
  // ⚠ 「降服**附属于该单位**」说的是**效应的来源**（降服），不是被影响的物件（单位）——
  //   一开始写成检查 o，结果永远不成立。条件问的是「来源现在的状态」。
  if (c.操作 === '附属在') return 来源?.附属在 !== undefined && 来源.附属在 === Number(c.目标);
  return 判断 ? 判断(条件) : true;   // 不认识的形状：不拦（宁可宽松，也不要静默失效）
}

/**
 * 初阵释疑：只有无双实体有无双名称；牌名中「·」后面那段，没有「·」则牌名即无双名称。
 * （放这里是因为两份筛选实现合并后都用到它。）
 */
export function 无双名称(o: Obj): string | null {
  if (!(o.def.超类别 ?? []).includes('无双')) return null;
  const n = o.def.全名;
  const i = n.indexOf('·');
  return i >= 0 ? n.slice(i + 1) : n;
}

/**
 * **取一个条件在**印制信息**（o.def）上的值。**
 * 只有 印制: true 的条件才走这里 —— 规则里写「**印制**类别为…」时用它。
 */
function 取印制值(o: Obj, a: 筛选属性): (string | number)[] {
  const d = o.def;
  switch (a) {
    case '类别': return d.类别;
    case '副类别': return d.副类别 ?? [];
    case '势力': return d.势力 ?? [];
    case '超类别': return d.超类别 ?? [];
    case '打出费用': {
    // ★ 统一后 打出费用 是 费用行为[]（或旧数字 / 'X'）→ 必须走 牌面费用值 取数 ✗ 不能再判 typeof
    //   108.3g：带 X 的牌在堆叠以外 X 视同 0 → 'X' 一律按 0 ✓
    const v = 牌面费用值(d.打出费用);
    return [v === 'X' ? 0 : v];
  }
    case '伤害': return [o.damage];
    case '名称': return d.名称;
    case '全名': return [d.全名];
    case '称号': return d.称号 ? [d.称号] : [];
    case '无双名称': { const w = 无双名称(o); return w === null ? [] : [w]; }
    case '灵值': return d.灵值 === undefined ? [] : [d.灵值];
    case '武力': return typeof d.武力 === 'number' ? [d.武力] : [];
    case '体力上限': return typeof d.体力上限 === 'number' ? [d.体力上限] : [];
    // ⚠ 关键词没有「印制」这一说 —— 它是能力不是特征（层6 也能授予）。
    default: return [];
  }
}

/** 取一个条件在**算出来的特征**（613 层系统之后）上的值 —— 也就是「现在状态」 */
function 取特征值(g: GameState | undefined, o: Obj, a: 筛选属性, f: 特征): (string | number)[] {
  const d = o.def;
  switch (a) {
    case '类别': return f.类别;
    case '副类别': return f.副类别;
    case '势力': return f.势力 ?? [];
    case '超类别': return f.超类别;
    case '打出费用': {
    // ★ 统一后 打出费用 是 费用行为[]（或旧数字 / 'X'）→ 必须走 牌面费用值 取数 ✗ 不能再判 typeof
    //   108.3g：带 X 的牌在堆叠以外 X 视同 0 → 'X' 一律按 0 ✓
    const v = 牌面费用值(d.打出费用);
    return [v === 'X' ? 0 : v];
  }
    case '伤害': return [o.damage];   // 120.5：已损失体力在 Obj 上，不在 特征 里
    // 「具有<某关键词>能力」—— 关键词是**算出来的**（层 6 也能授予），
    //   所以拿规则书里所有关键词的名字逐个问 有词()，取命中的那些。
    case '关键词': return g ? Object.keys(关键词解析表).filter((k) => 具有关键词(g, o, k)) : [];
    case '名称': return [f.名称];
    case '全名': return [d.全名];
    case '称号': return d.称号 ? [d.称号] : [];
    // 初阵释疑：只有无双实体有无双名称；牌名中「·」后面那段，没有「·」则牌名即无双名称
    case '无双名称': { const w = 无双名称(o); return w === null ? [] : [w]; }
    case '灵值': return d.灵值 === undefined ? [] : [d.灵值];
    case '武力': return [f.武力];
    case '体力上限': return [f.体力上限];
  case '区域': return [o.区域];
  // 506-510：这张牌是不是**本次战斗的进攻单位**
  case '进攻中': return [g?.当前进攻者 === o ? 1 : 0];
  // 区域内的位置：牌库末尾 = 顶（抓牌从末尾取），下标 0 = 底。
  //   ⚠ 其他区域（手牌/墓地/放逐区/战场）没有规则定义的顺序 → 返回空（筛选永不匹配），不猜。
  case '距顶': {
    if (o.区域 !== '牌库' || !g) return [];
    const lib = g.players[o.owner]?.library ?? [];
    const idx = lib.indexOf(o);
    return idx < 0 ? [] : [lib.length - idx];
  }
  case '距底': {
    if (o.区域 !== '牌库' || !g) return [];
    const lib = g.players[o.owner]?.library ?? [];
    const idx = lib.indexOf(o);
    return idx < 0 ? [] : [idx + 1];
  }
    case '面': return [o.面];
    case '已横置': return [o.tapped ? 1 : 0];
    default: return [];
  }
}

/** 单个条件的比较 —— 值由 c.印制 决定取哪一边 */
function 符合一个条件(g: GameState, o: Obj, c: 筛选条件, f: 特征, 记忆源?: Obj,
  锚?: Obj | null, 控制器?: number, 触发受方?: Obj | number): boolean {
  // ★ B：关系/几何/状态类条件也走 筛选 ✓（它们不是"特征值"，要锚/控制器/触发受方 ✓）
  const 符合种类0 = (k: string): boolean =>
    k === '实体' || k === '物件' ? true : k === '令符' ? false : (f.类别 as string[]).includes(k);
  switch (c.属性) {
    case '自身': return o === (锚 ?? null);
    case '除自身': return o !== (锚 ?? null);
    case '所附属': return !!锚 && 锚.附属在 !== undefined && 锚.附属在 === o.uid;
    case '所佩带': return !!锚 && 锚.佩带在 !== undefined && 锚.佩带在 === o.uid;
    case '种类': return 符合种类0(String(c.值 ?? ''));
    case '非种类': return !符合种类0(String(c.值 ?? ''));
    case '相对阵地为空': {
      const 对面 = o.阵地 ? g.players[1 - 有效控制器(g, o)]?.阵地[相对阵地(o.阵地)!] : null;
      /**
       * 默认（不写值）= 「对面空着」；`值: false` / `比较: '不是'` = **已对阵**（对面有单位）。
       * ⚠ 以前这里**值不看** → 只能表达「未对阵」，063 迎头痛击就录不了。
       */
      const 要空 = c.比较 === '不是' ? false
        : c.值 === undefined ? true
        : !(c.值 === '否' || c.值 === 0);
      return 要空 ? !对面 : !!对面;
    }
    case '附属于':
      return !!锚 && o.附属在 === 锚.uid;
    case '佩带于':
      return !!锚 && o.佩带在 === 锚.uid;
    case '操控者': {
      const 控 = 有效控制器(g, o);
      // 值可以是 { 记忆: 键 }：读记住的玩家号（096「目标玩家的单位」）
      if (c.值 && typeof c.值 === 'object' && '记忆' in c.值) {
        const 存 = 记忆源?.记忆?.[(c.值 as { 记忆: string }).记忆];
        return typeof 存 === 'number' ? 控 === 存 : false;
      }
      // 数字 = 具体玩家号（来自 {目标}/{记忆} 代换）
      if (typeof c.值 === 'number') return 控 === c.值;
      if (c.值 === undefined) return false;
      const 谁 = String(c.值);
      if (控制器 === undefined) return false;
      if (谁 === '你') return 控 === 控制器;
      if (谁 === '对手') return 控 !== 控制器;
      if (谁 === '该玩家') {
        if (触发受方 === undefined) return false;
        const 该 = typeof 触发受方 === 'number' ? 触发受方 : 有效控制器(g, 触发受方);
        return 控 === 该;
      }
      return false;
    }
    case '关系': {
      if (!锚 || !锚.阵地) return false;
      // 值可以是数组：「相对或斜对」
      const 名们 = (Array.isArray(c.值) ? c.值 : [c.值 ?? '相对']).map(String);
      const 锚阵地 = 锚.阵地;
      const 自己 = g.players[锚.操控者]!;
      const 敌 = g.players[(锚.操控者 + 1) % g.players.length]!;
      const 允许: (Obj | null)[] = [];
      for (const 名 of 名们) {
        if (名 === '相对') 允许.push(敌.阵地[相对阵地(锚阵地)!]);
        else if (名 === '相邻') 允许.push(...相邻阵地(锚阵地).map((x) => 自己.阵地[x]));
        else 允许.push(...斜对阵地(锚阵地).map((x) => 敌.阵地[x]));
      }
      return 允许.includes(o);
    }
    default: break;
  }
  const 有的 = c.印制 ? 取印制值(o, c.属性) : 取特征值(g, o, c.属性, f);
  // 「值」可以是**记住**下来的数（074 一夫当关「武力小于**该单位**」= 先记住它的武力）
  const 解一 = (v: unknown): string | number => (v && typeof v === 'object' && '记忆' in v)
    ? Number(记忆源?.记忆[String((v as { 记忆: string }).记忆)] ?? 0) : (v as string | number);
  const 值列: (string | number)[] = (c.值 === undefined ? [] : (Array.isArray(c.值) ? c.值 : [c.值])).map(解一);
  switch (c.比较 ?? '是') {
    case '是': return 值列.length === 0 ? 有的.length > 0 : 值列.some((v) => 有的.includes(v));
    case '不是': return !值列.some((v) => 有的.includes(v));
    case '包含': return 值列.some((v) => 有的.some((x) => String(x).includes(String(v))));
    case '不含': return !值列.some((v) => 有的.some((x) => String(x).includes(String(v))));
    case '大于': return 有的.some((x) => typeof x === 'number' && typeof 值列[0] === 'number' && x > 值列[0]);
    case '小于': return 有的.some((x) => typeof x === 'number' && typeof 值列[0] === 'number' && x < 值列[0]);
    // 128 张宝「费用值**小于等于**2」—— 不要拿「小于 3」凑，那是同一件事的第二种写法
    case '小于等于': return 有的.some((x) => typeof x === 'number' && typeof 值列[0] === 'number' && x <= 值列[0]);
    case '大于等于': return 有的.some((x) => typeof x === 'number' && typeof 值列[0] === 'number' && x >= 值列[0]);
    default: return false;
  }
}

/**
 * **筛选条件的唯一求值器。**
 *
 * 值从哪来由**每个条件自己**决定：
 *   · 不写 `印制`（默认）= **现在状态** —— 层算完之后的特征 `f`（613：受前面层影响）；
 *   · 写 `印制: true` = **印制信息** `o.def` —— 规则里写「**印制**类别为…」时用它
 *     （屯骑营「一个由你操控且印制类别为基本领土的暗置领土」）。
 *
 * ⚠ 以前这件事有**两份实现**：engine.ts 的 `符合一个条件` 读 `o.def`，
 *   这里的 `特征符合` 读 `f`。同一个 `筛选` 在两个调用路径上结论**相反** ——
 *   「超类别=基本」对着暗置的领土：走触发（engine）判通过、走目标选择（这里）判不通过。
 *   现在合并成一份，语义**只由 `印制` 决定**。
 *
 * `f` 不给就现算（要 `判断` 回调求值「只要…」条件；engine 那边有）。
 */
/** 筛选的主体域 —— 同一个条件结构，按域求值 */
export type 筛选域 = '物件' | '玩家' | '阵地';

/** 判定上下文：锚/触发受方/记忆源都从 item 来，数据只写条件 */
export interface 判定上下文 {
  g: GameState;
  控制器: number;
  item?: StackItem;
  锚?: Obj | null;
  触发受方?: Obj | number;
  记忆源?: Obj;
  /** 已经算好的特征（目标选择那边会传，省一次重算） */
  特征?: 特征;
  /** 阵地域：这个阵地属于谁的半场 */
  半场?: number;
}

function 比较数或值(有的: number | string, c: 筛选条件): boolean {
  const 比较 = c.比较 ?? '是';
  const 列 = Array.isArray(c.值) ? c.值 : [c.值];
  switch (比较) {
    case '是': return 列.some((v) => String(v) === String(有的));
    case '不是': return !列.some((v) => String(v) === String(有的));
    case '大于': return 列.some((v) => typeof v === 'number' && typeof 有的 === 'number' && 有的 > v);
    case '大于等于': return 列.some((v) => typeof v === 'number' && typeof 有的 === 'number' && 有的 >= v);
    case '小于': return 列.some((v) => typeof v === 'number' && typeof 有的 === 'number' && 有的 < v);
    case '小于等于': return 列.some((v) => typeof v === 'number' && typeof 有的 === 'number' && 有的 <= v);
    default: return false;
  }
}

function 符合玩家条件(ctx: 判定上下文, p: number, c: 筛选条件): boolean {
  const pl = ctx.g.players[p];
  if (!pl) return false;
  switch (c.属性) {
    case '种类': return (Array.isArray(c.值) ? c.值 : [c.值]).includes('玩家');
    case '座位': return 比较数或值(p, c);
    case '体力': return 比较数或值(pl.体力, c);
    case '体力上限': return 比较数或值(pl.lifeMax, c);
    case '手牌数': return 比较数或值(pl.hand.length, c);
    case '操控者': {
      const 谁 = String(c.值 ?? '你');
      const 是 = 谁 === '你' ? p === ctx.控制器 : 谁 === '对手' ? p !== ctx.控制器 : p === Number(谁);
      return (c.比较 ?? '是') === '不是' ? !是 : 是;
    }
    default: return false;
  }
}

function 符合阵地条件(ctx: 判定上下文, s: 阵地, c: 筛选条件): boolean {
  const 主 = ctx.半场 ?? ctx.控制器;
  switch (c.属性) {
    case '空': {
      const 空 = !ctx.g.players[主]?.阵地[s];
      return String(c.值) === 'false' || c.比较 === '不是' ? !空 : 空;
    }
    case '归属者': {
      const 谁 = String(c.值 ?? '你');
      const 是 = 谁 === '你' ? 主 === ctx.控制器 : 谁 === '对手' ? 主 !== ctx.控制器 : 主 === Number(谁);
      return (c.比较 ?? '是') === '不是' ? !是 : 是;
    }
    case '关系': {
      const 锚位 = ctx.锚 && ctx.锚.阵地 ? ctx.锚.阵地 : null;
      if (!锚位) return false;
      const 值 = String(c.值 ?? '相邻');
      const 位 = 值 === '相邻' ? 相邻阵地(锚位)
        : 值 === '斜对' ? 斜对阵地(锚位)
        : 值 === '相对' ? [相对阵地(锚位)].filter((x): x is 阵地 => x !== null)
        : [];
      return 位.includes(s);
    }
    default: return false;
  }
}

/** 唯一求值入口：按域分派（物件走现成的 符合筛选） */
export function 符合域(ctx: 判定上下文, 主体: Obj | number | 阵地, 域: 筛选域, 条件?: 筛选): boolean {
  if (!条件 || !条件.length) return true;
  if (域 === '物件') {
    return 符合筛选(ctx.g, 主体 as Obj, 条件, ctx.特征, undefined, ctx.记忆源, ctx.锚 ?? null, ctx.控制器, ctx.触发受方);
  }
  if (域 === '玩家') return 条件.every((c) => 符合玩家条件(ctx, 主体 as number, c));
  return 条件.every((c) => 符合阵地条件(ctx, 主体 as 阵地, c));
}

export function 符合筛选(g: GameState, o: Obj, 条件表?: 筛选, f?: 特征, 判断?: 条件判断, 记忆源?: Obj,
  锚?: Obj | null, 控制器?: number, 触发受方?: Obj | number): boolean {
  if (!条件表 || 条件表.length === 0) return true;
  const 特征 = f ?? 计算特征(g, o, 判断);
  return 条件表.every((c) => 符合一个条件(g, o, c, 特征, 记忆源, 锚, 控制器, 触发受方));
}

/**
 * ⚠ **递归保护**（和 有效控制器 的 `算操控权中` 同一个道理）。
 *
 * 环是这么绕回来的：
 *   计算特征 → 无能力集合 / 适用 → 匹配 → 条件成立 → 判断
 *     → 取值（`{ 数: 选择器 }`）→ 候选目标 → **有词** → 有效特征 → 计算特征 …
 *
 * 【魏武精兵】那种「只要你操控 3 个以上魏领土」的条件走的正是 `{ 数: … }`，
 * 于是算它的特征会无限递归、栈溢出。同一个物件在算的过程中直接给**基础特征**
 * —— 604.3 的「印制信息」本来就是这个计算的起点。
 */
const 算特征中 = new Set<number>();
let 算特征深度 = 0;

/**
 * 计算一个物件的当前特征（613）。
 * 判断：可选的「只要…」条件求值器（由引擎注入，避免循环依赖）
 */

export function 计算特征(g: GameState, o: Obj, 判断?: 条件判断): 特征 {
  return 计算到层(g, o, 7, 判断);
}

/**
 * **按层算**：只折到第 `上限层` 层。
 *
 * 为什么要有它：特征的每一层**只依赖 ≤ 自己** 的层（层4 类别、层5 势力、层6 能力、层7 武力）。
 *   层 2 的改操控权效应只需要「层 2 之前」的特征。以前它调的是完整 计算特征，于是：
 *     ① 问一次操控者 = 把武力、关键词、层 6 全部算完 —— 一次属性访问触发整个世界重算；
 *     ② **层序是错的** —— 层 2 的效应看到了层 4/6/7 之后的样子，而它本该看不到。
 *   按层切开之后依赖图严格向下，层 2 的匹配到「别人的层 2」为止，不再倒回来要层 7。
 *
 * ⚠ 递归保护（算特征中）仍然按 **uid** 记，不按层 —— 同一物件在算层2 时若有人要它的
 *   完整特征，回落到 基础特征（宁可保守，也不要绕回去）。
 */
/** ⚠ 当前正在折叠到哪一层 —— 嵌套的条件查询只许看到 ≤ 这一层（613 层拓扑序 ✓） */
const 层栈: number[] = [];
export function 当前上限层(): number { return 层栈.length ? 层栈[层栈.length - 1]! : 7; }

export function 计算到层(g: GameState, o: Obj, 上限层: number, 判断?: 条件判断): 特征 {
  if (算特征中.has(o.uid)) return 基础特征(o);          // ⚠ 上下文相关 → **不进 memo** ✓
  const s = 取快照(g);
  const 用判断 = 判断 !== undefined;
  /**
   * ⚠ **只有"真物件"才进 memo** ✓ —— 键是 `uid:层:判断` ✓，所以**没有 uid 的伪物件**
   *   （`实际打出费用` 用的 `{ def } as Obj` ✓、筛选/条件里那种"只是想问 def"的 ✓）
   *   **必须每次现算** ✗→✓。
   *   否则所有伪物件共用 `undefined:…` 这一格 ✗ → **先问谁就返回谁的特征** ✗
   *   （2026-10 实锤：【天监智囊】「只对锦囊 −2」被算成"任何牌都减" ✗ ——
   *     单位拿着先问过的【看破】的特征 ✓ 通过了"类别=锦囊"的筛选 ✓、
   *     再吃 −2 被 `max(0, …)` 夹成 0 ✓，看起来就是"第一个令符 −1" ✓）。
   */
  const 可缓存 = typeof o.uid === 'number';
  const 键 = o.uid + ':' + 上限层 + ':' + (用判断 ? 1 : 0);
  if (可缓存 && !s.构建中) {
    const 有 = s.特征.get(键);
    if (有) return 有;
  }
  算特征中.add(o.uid);
  算特征深度++;
  层栈.push(上限层);
  try {
    // ⚠ **条件始终求值** ✓（原来「嵌套一层就不求」✗ = 深层条件静默按「不拦」✓→✗）。
    //   不会指数爆炸，因为：① 结果进了 memo（每个 (uid, 层, 是否带判断) 每版本只算一次 ✓）；
    //   ② 嵌套查询被 `当前上限层()` 限制在 ≤ 本层 ✓ → 跨层严格递减 ✓；
    //   ③ 同层回环由 `算特征中` 兜住（回到 基础特征 ✓）。
    const 值 = 计算特征内(g, o, 判断, 上限层);
    if (可缓存 && !s.构建中) s.特征.set(键, 值);           // 构建期间算出来的**不写** ✓（见 取快照 的说明 ✓）
    return 值;
  } finally { 层栈.pop(); 算特征中.delete(o.uid); 算特征深度--; }
}
/* ── 派生快照 ────────────────────────────────────────────────────
   ⚠ **按 `g` 键**（`WeakMap` ✓），不是模块级单槽 ✗ —— 单槽在多房间下会互相冲刷 ✓，
     而且模块级状态在引擎异步化之后会跨房串味 ✓。
   ⚠ 唯一失效依据是 `g.状态版本` ✓（由 `state.ts` 的 mutator 里 `盖章(g)` 自增 ✓）。
     写入点已经由**类型**锁死（`readonly` + 唯一 mutator ✓）→ 漏失效不可能发生 ✓。
   ⚠ `构建中` 期间**不读也不写** memo ✓：
     `无能力集合` 要跑 `匹配`，而匹配会经条件/筛选绕回 `计算特征` ✗ ——
     那些回绕算出来的特征是在「无能力还是空集」的假设下算的 ✓，写进 memo 就是错的 ✗。
   ⚠ `计算到层` 早退那一条（`算特征中.has(uid)` → 基础特征）**不进 memo** ✓（它跟上下文有关 ✓）。 */
type 层键 = '层4' | '层5' | '层6' | '层7a' | '层7b' | '层7c' | '层7d';
interface 快照 {
  版本: number;
  候选: 候选效应[];
  可用候选: 候选效应[];                      // 已经剔除「来源失去能力」的那些 ✓
  无能力: Set<number>;
  桶: Partial<Record<层键, 候选效应[]>>;
  特征: Map<string, 特征>;
  操控者: Map<number, number>;
  构建中: boolean;
}
const 快照表 = new WeakMap<GameState, 快照>();

function 取快照(g: GameState): 快照 {
  const 版本 = g.状态版本 ?? 0;
  const 旧 = 快照表.get(g);
  if (旧 && 旧.版本 === 版本) return 旧;
  const s: 快照 = { 版本, 候选: [], 可用候选: [], 无能力: new Set(), 桶: {}, 特征: new Map(), 操控者: new Map(), 构建中: true };
  快照表.set(g, s);                          // ⚠ **先挂上再算**：下面两步可能重入 ✓（重入会拿到 构建中 的快照 ✓）
  s.候选 = 收集候选(g);
  s.无能力 = 无能力集合(g, s.候选);
  s.可用候选 = s.候选.filter((c) => !(c.来源 && s.无能力.has(c.来源.uid)));
  s.构建中 = false;
  return s;
}

function 计算特征内(g: GameState, o: Obj, 判断?: 条件判断, 上限层 = 7): 特征 {
  const f = 基础特征(o);
  const s = 取快照(g);
  const 候选表 = s.候选;

  // 604.3：特征定义能力在所有区域生效；其它持续性效应只在战场生效
  const 在战场 = o.区域 === '战场';

  // 层6：失去所有能力的物件，以及它作为来源产生的效应，都要剔除
  // （613.6 的例外没有完整建模：一个效应若已在前面的层生效，本应继续生效）
  const 无能力 = s.无能力;
  const 失去能力 = 无能力.has(o.uid);
  const 候选 = s.可用候选;
  f.失去所有能力 = 失去能力 || f.失去所有能力;

  // ⚠ 层分桶：一个物件要问 8 个层，每次 `候选.filter(谓)` 都是全场扫描 ✗
  //   → 桶按**状态版本**存活 ✓（和候选表同一个失效语义 ✓），各层只遍历自己的桶 ✓
  const 桶 = (键: 层键, 谓: (c: 候选效应) => boolean): 候选效应[] => (s.桶[键] ??= 候选.filter(谓));
  void 候选表;
  const 适用 = (键: 层键, 谓: (c: 候选效应) => boolean): 候选效应[] =>
    桶(键, 谓).filter((c) => (在战场 || c.是特征定义) && 匹配(g, c, o, f, 判断))
      .sort((a, b) => a.时间印记 - b.时间印记);

  // 层4：类别 / 副类别 / 超类别
  if (上限层 >= 4) for (const c of 适用('层4', (x) => x.层.类别 !== undefined || x.层.副类别 !== undefined || x.层.超类别 !== undefined || x.层.增加副类别 !== undefined)) {
    if (c.层.类别) f.类别 = c.层.类别.slice();
    if (c.层.超类别) f.超类别 = c.层.超类别.slice();
    if (c.层.副类别) f.副类别 = c.层.副类别.slice();
      // 层4「额外具有」= **并上**（上面那条是替换）—— 例：171 黄头巾「额外具有黄巾此类别」
      if (c.层.增加副类别?.length) f.副类别 = [...new Set([...f.副类别, ...c.层.增加副类别])];
  }
  // 层5：势力
  if (上限层 >= 5) for (const c of 适用('层5', (x) => x.层.势力 !== undefined)) f.势力 = c.层.势力!.slice();
  // 层6：能力（613.3 特征定义能力先行，再按时间印记）
  const 层6 = (上限层 >= 6 ? 适用('层6', (x) => x.层.获得关键词 !== undefined || x.层.失去所有能力 !== undefined
    || x.层.授予动作 !== undefined || x.层.不能重置 !== undefined || x.层.必须发起战斗 !== undefined
    || x.层.不能启动能力 !== undefined || x.层.获得能力 !== undefined) : []);
  层6.sort((a, b) => Number(b.是特征定义) - Number(a.是特征定义) || a.时间印记 - b.时间印记);
  for (const c of 层6) {
    if (c.层.失去所有能力) { f.失去所有能力 = true; }
    // 034 一蹶不振：「所附属之单位于其操控者的重置步骤中不能重置」
    if (c.层.不能重置) { f.不能重置 = true; }
    if (c.层.必须发起战斗) { f.必须发起战斗 = true; }
    if (c.层.不能启动能力) { f.不能启动能力 = true; }
    if (c.层.获得能力) { f.获得能力 = [...f.获得能力, ...c.层.获得能力]; }
    // 702.1d：授予就是**把这个关键词能力加到它身上** —— 追加，**不去重**
    //   （702.6d 那批：多个同名关键词是多个各自独立的能力；吕范的例子就是两个射击2）
    if (c.层.获得关键词) {
      // ⚠ 条目**原样收下**（名称和数值都是字段了，没有尾巴要解析）
      f.关键词 = [...f.关键词, ...c.层.获得关键词.map((k) => ({ ...k, 印制: false }))];
    }
    // 授予的动作按**动作名**去重（同一个动作被授两次不叠加），后授的覆盖先授的
    if (c.层.授予动作) {
      for (const a of c.层.授予动作) {
        f.授予动作 = [...f.授予动作.filter((x) => x.动作 !== a.动作), a];
      }
    }
  }
  if (上限层 < 7) return f;   // 只算到层6 为止
  // 层7a：特征定义能力（定义武力/体力）—— 613.4a
  for (const c of 适用('层7a', (x) => x.层.定义武力 !== undefined || x.层.定义体力 !== undefined)) {
    if (c.层.定义武力 !== undefined) f.武力 = 层值(c.层.定义武力, o, g);
    if (c.层.定义体力 !== undefined) f.体力上限 = 层值(c.层.定义体力, o, g);
  }
  // 层7b：设定为特定值
  for (const c of 适用('层7b', (x) => x.层.设定武力 !== undefined || x.层.设定体力 !== undefined)) {
    if (c.层.设定武力 !== undefined) f.武力 = typeof c.层.设定武力 === 'number' ? c.层.设定武力 : 0;
    if (c.层.设定体力 !== undefined) f.体力上限 = typeof c.层.设定体力 === 'number' ? c.层.设定体力 : 0;
  }
  // 层7c：增减（含标记）
  for (const c of 适用('层7c', (x) => x.层.增减武力 !== undefined || x.层.增减体力 !== undefined)) {
    // 层 7c 的数值可以是固定数，也可以是 Value（用**这个层所属效应的来源**当记忆源）
    f.武力 += 层值(c.层.增减武力 ?? 0, c.来源);
    f.体力上限 += 层值(c.层.增减体力 ?? 0, c.来源);
  }
  // 层7d：交换
  for (const c of 适用('层7d', (x) => x.层.交换武力体力 === true)) {
    const t = f.武力; f.武力 = f.体力上限; f.体力上限 = t;
  }
  f.武力 = Math.max(0, f.武力);
  f.体力上限 = Math.max(0, f.体力上限);
  return f;
}

function 找实体(g: GameState, uid: number): Obj | undefined {
  for (const o of g.战场) if (o.uid === uid) return o;
  return undefined;
}

/** 这个物件当前是否属于某个牌类别（层4 生效后） */
export function 属于类别(g: GameState, o: Obj, 类别: CardType, 判断?: 条件判断): boolean {
  return 计算特征(g, o, 判断).类别.includes(类别);
}

/** 这个物件当前是否具有某个关键词能力（层6 生效后） */
export function 具有关键词(g: GameState, o: Obj, 关键词: string, 判断?: 条件判断): boolean {
  return 计算特征(g, o, 判断).关键词.some((k) => k.名称 === 关键词);
}
