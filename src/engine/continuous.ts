const 关键词标记表 = new Set(['洞察', '重整', '破竹', '强进', '隐匿', '斩获', '致命', '转移']);

/** 709.2 / 709.2a：暗置的实体没有特征，只成为一张「暗置领土」 */
function 基础特征(o: Obj): 特征 {
  if (o.面 === '暗置') {
    return {
      名称: '暗置领土', 超类别: [], 类别: ['领土'], 副类别: [],
      势力: null, 武力: 0, 体力上限: 0, 关键词: [], 失去所有能力: false, 不能重置: false, 必须发起战斗: false, 不能启动能力: false, 获得能力: [], 暗置: true, 授予动作: [],
    };
  }
  const d = o.def;
  return {
    名称: d.名称[0] ?? d.全名,
    超类别: (d.超类别 ?? []).slice(),
    类别: (d.类别 ?? []).slice(),
    副类别: (d.副类别 ?? []).slice(),
    势力: d.势力 ? d.势力.slice() : null,
    武力: typeof d.武力 === 'number' ? d.武力 : 0,
    体力上限: typeof d.体力上限 === 'number' ? d.体力上限 : 0,
    // 702.1：**关键词就是能力** —— 牌面能力里那些「只写了名称的」条目，
    //   解析时会认出它是关键词（能解析）。这里把它们登记成印制的关键词条目。
    //   ⚠ 不需要在卡数据里额外写一份声明：写了 能力: [{ 名称:'转移' }] 就是声明。
    关键词: ((d.能力?.能力 ?? []) as { 名称?: string; 数值?: number; 特征?: 筛选 }[])
      .filter((ab) => ab.名称 !== undefined && 能解析(ab.名称))
      // ⚠ `特征` 也要带上（702.2 抵抗 / 702.5 附属那种**带特征参数**的关键词）。
      //   漏了它，印制的抵抗会退化成 702.2d 的「万物抵抗」—— 拦得比该拦的多。
      .map((ab) => ({ 名称: ab.名称!, ...(ab.数值 !== undefined ? { 数值: ab.数值 } : {}), ...(ab.特征 !== undefined ? { 特征: ab.特征 } : {}), 印制: true })),
    失去所有能力: false,
    不能重置: false,
    必须发起战斗: false,
    不能启动能力: false,
    获得能力: [],
    暗置: false,
    授予动作: [],
  };
}

/** 收集全场所有静止式能力产生的持续性效应 + 已产生的连续性效应 + 标记 */
function 收集候选(g: GameState): 候选效应[] {
  const out: 候选效应[] = [];
  // 战场是一个**共享区域** —— 直接遍历，不按玩家分
  for (const o of g.战场) {
    {
      // 709.2a：暗置的实体没有规则叙述，因此不产生任何持续性效应
      if (o.面 === '暗置') continue;
      const abs = (o.def.能力?.能力 ?? []) as {
        种类?: string;
        连续?: { 范围?: Selector; 筛选?: 筛选; 层: 层修改; 条件?: unknown };
        自身加成?: { 每个其他同名: { 武力?: number; 体力上限?: number } };
      }[];
      // 702.28b 同袍：「对此单位和与其**相邻**且与其具**共通副类别**的每个单位而言，
      //   只要它们之一具有某个**非同袍的印制关键词能力**，则他们皆具有该关键词能力。」
      // ⚠ 这里**直接读 def.能力**，不能调 有词（那会回到 计算特征 → 死循环）
      if (((o.def.能力?.能力 ?? []) as { 名称?: string }[]).some((x) => x.名称 === '同袍') && o.阵地) {
        const 自己 = g.players[o.操控者]!;
        const 邻 = 相邻阵地(o.阵地).map((s) => 自己.阵地[s])
          .filter((x): x is Obj => !!x && x !== o);
        // 「具共通副类别」
        const 共通 = 邻.filter((x) => x.def.副类别.some((c) => o.def.副类别.includes(c)));
        const 借 = new Set<string>();
        for (const x of [o, ...共通]) {
          for (const y of (x.def.能力?.能力 ?? []) as { 名称?: string }[]) {
            if (y.名称 && y.名称 !== '同袍') 借.add(y.名称);       // 「非同袍的」
          }
        }
        if (借.size) {
          out.push({
            时间印记: o.时间印记, 来源: o, 控制器: o.操控者, 指定: o,
            层: { 获得关键词: [...借].map((名) => ({ 名称: 名 })) }, 是特征定义: false,
          });
        }
      }
      // 这里**不解析**关键词能力：静止式的关键词都是「遇到才检查」（有词 / 词值），
      //   不产生候选效应。所以 kindless 的条目没有 种类、会被下面这行跳过。
      for (const ab of abs) {
        if (ab.种类 !== '静止式') continue;
        if (ab.连续) {
          out.push({
            时间印记: o.时间印记, 来源: o, 控制器: o.操控者,
            范围: ab.连续.范围, 筛选: ab.连续.筛选, 层: ab.连续.层,
            是特征定义: ab.连续.层.定义武力 !== undefined || ab.连续.层.定义体力 !== undefined,
            条件: ab.连续.条件,
          });
        }
        if (ab.自身加成) {
          // 604.3 特征定义能力：武力 = 印制值 + 每个「其他同名」的加成（层 7a）
          //
          // ⚠ 卡面是「只要你**操控**其他【同名】」—— **计数必须只算同一个操控者的**。
          //   以前这里只比名字、**没比操控者**，于是**对手**打出同名单位也会给你 +1
          //   （【魏新兵】就撞上过：对方打出魏新兵，我这边的魏新兵白涨 1 点武力）。
          //   用 有效控制器 而不是 o.操控者 —— 操控权可能被效应改过。
          // ⚠ **不能调 有效控制器** —— 它 → 计算特征 → 收集候选 → 又回到这里；
          //   而防重入（算操控权中）只保护**同一个 uid**，遍历到的每个 x 都不一样，挡不住 → 死循环。
          //   打出【魏新兵】卡死就是这么来的。和上面 702.28b 同袍那条一样：只读**基础操控者**。
          const 我 = o.操控者;
          const 其他 = g.战场.filter((x) =>
            x !== o && x.操控者 === 我 && x.def.名称.some((n) => o.def.名称.includes(n))).length;
          out.push({
            时间印记: o.时间印记, 来源: o, 控制器: o.操控者,
            // 必须限定「自身」—— 少了它，这条定义会套到**全场**同名单位上：
            //   最后一项（时间印记最晚的）赢，于是对手的魏新兵会把你的武力也改掉。
            //   「自身」在 符合选择器 里判的是 o === 锚，锚就是上面的 来源。
            范围: { 筛选: [{ 属性: '区域', 值: '战场' }, { 属性: '种类', 值: '单位' }, { 属性: '自身' }] },
            层: {
              定义武力: (typeof o.def.武力 === 'number' ? o.def.武力 : 0) + (ab.自身加成.每个其他同名.武力 ?? 0) * 其他,
              定义体力: (typeof o.def.体力上限 === 'number' ? o.def.体力上限 : 0) + (ab.自身加成.每个其他同名.体力上限 ?? 0) * 其他,
            },
            是特征定义: true,
          });
        }
      }
      // 122.1b：实体上的关键词标记会让它获得该关键词能力（层6）
      const 关键词标记 = (o.标记 ?? []).filter((m) => 关键词标记表.has(m.类型));
      if (关键词标记.length) {
        out.push({
          时间印记: Math.min(...关键词标记.map((m) => m.时间印记)), 来源: o, 控制器: o.操控者,
          层: { 获得关键词: 关键词标记.map((m) => ({ 名称: m.类型 })) }, 是特征定义: false,
        });
      }
      // 613.7c：标记在放置时得到时间印记
      for (const m of o.标记 ?? []) {
        if (m.类型 === '+1/+1') {
          out.push({ 时间印记: m.时间印记, 来源: null, 控制器: o.操控者, 指定: o,
            层: { 增减武力: m.数量, 增减体力: m.数量 }, 是特征定义: false });
        } else if (m.类型 === '-1/-1') {
          out.push({ 时间印记: m.时间印记, 来源: null, 控制器: o.操控者, 指定: o,
            层: { 增减武力: -m.数量, 增减体力: -m.数量 }, 是特征定义: false });
        }
      }
    }
  }
  // 611.2 结算产生的持续性效应
  for (const e of g.连续效应 ?? []) {
    // **载荷各取所需**：这里只关心「层」（算特征时用）；
    //   「替代」那一半由伤害管线自己读（见 收集伤害替代效应）—— 两条路读**同一个记录**。
    if (!e.载荷.层) continue;
    out.push({
      时间印记: e.时间印记, 来源: e.来源, 控制器: e.控制器, 范围: e.范围,
      层: e.载荷.层, 是特征定义: false,
      指定: e.指定 === undefined ? undefined : 找实体(g, e.指定), 指定uid: e.指定,
      受锁定: e.受锁定, 条件: e.条件,
    });
  }
  // 「直到回合结束」的临时效应（也是层 7c）
  for (const e of g.tempEffects ?? []) {
    if (e.种类 !== '加成') continue;
    out.push({ 时间印记: e.时间印记 ?? 0, 来源: null, 控制器: 0, 指定: e.target,
      层: { 增减武力: e.武力, 增减体力: e.体力上限 }, 是特征定义: false });
  }
  return out;
}

/**
 * 层6 的「失去所有能力」是全场性的：一个物件失去所有能力后，它作为来源产生的持续性效应也停止。
 * 先扫一遍全场算出这个集合，再据此剔除候选效应。
 * （用基础特征做筛选判断，不追层4/5 的改变，属于简化）
 */
function 无能力集合(g: GameState, 候选表: 候选效应[]): Set<number> {
  const s = new Set<number>();
  // ⚠ **先把「失去所有能力」这一类筛出来** ✓ —— 原来内层直接 `for (const c of 候选表)`，
  //   而 99% 的候选会撞上 `if (!c.层.失去所有能力) continue` 被跳过 ✗，却是**每个物件都遍历一遍** ✓
  //   → 单次成本 = 物件 × 候选（候选本身 ≈ 物件 × 能力）= O(n²)，而本函数**每个物件算特征都要跑一次** ✗
  //   → 采样实测占非空闲 CPU **26.9%（第一名）** ✓。
  //   筛出来之后内层只遍历这几个（通常 0~2 个）✓；**判据一字未改** ✓（同样的 匹配 / 同样「不能靠自己」✓）。
  const 剥能力 = 候选表.filter((c) => c.层.失去所有能力);
  if (!剥能力.length) return s;               // 没有这类候选 → 谁都不会失去能力（开局/多数局面就是这条 ✓）
  for (const x of g.战场) {
    {
      const 基础 = 基础特征(x);
      for (const c of 剥能力) {
        if (c.来源 === x) continue;               // 不能靠自己让自己失去能力
        // ⚠ **这里不传判断** —— 这只是「先扫一遍全场」的预处理，不是最终判定。
        //   传了判断的话，条件求值会走：取值({数:选择器}) → 候选目标 → 有词
        //   → 有效特征 → 计算特征 —— 而 计算特征 又会调回 无能力集合，
        //   战场上 N 个物件就是 **N 的幂**，直接卡死（8 块领土就能挂住）。
        //   本函数开头的注释本来就说了这里「用基础特征做筛选判断…属于简化」。
        if (匹配(g, c, x, 基础)) { s.add(x.uid); break; }
      }
    }
  }
  return s;
}

