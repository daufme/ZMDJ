/**
 * **合法动作清单** —— 「这个玩家现在能做什么，每件事有哪些合法目标」。
 *
 * 界面上的每个按钮都由这里生成；`engine.ts` 里的 `应用动作` 负责**再校验一次**。
 * 两层是分开的：这里只负责「列出来给玩家看」，那里才是「真的执行」。
 *
 * 为什么要有这一层：卡牌游戏的合法动作是**算出来的**，不是写死的 ——
 * 「能打哪块地」要看时机（304.1）、「能打哪张牌」要看费用与目标（601.2）、
 * 「能移到哪」要看是 702.16 的转移还是 116.2c 授予的移动（两者次数、目的地都不同）。
 * 界面不可能自己算这些，所以全部集中在这里，用和引擎同一组判定函数。
 *
 * ⚠ 这里**不做任何状态修改** —— 纯查询。有副作用就完了（界面刷新一次会调它很多次）。
 */
import type { GameState } from './state.js';
import { 相对阵地 } from './state.js';
import type { 阵地 } from './types.js';
import { 阵地顺序 } from './types.js';
import { 解析能力, 有效控制器 } from './continuous.js';
import type { ActivatedAbility } from './types.js';
import {
  能打出领土, 能施放, 候选目标, 能转移, 能移动许可, 转移关键词目标, 许可目标, 转移目标, 可支付数字费用,能发起战斗, 合法攻击对象, 可用启动式能力, 处于通常时机,
  type 时机选项,
  可支付上限, 实际打出费用, 有词, 能填满所有槽,
} from './engine.js';
import { 费用点数形状, 牌面费用值, 取费用行为, 支付费用 } from './费用.js';

export interface 候选 {
  /**
   * `实体` = 牌/实体；`玩家` = 玩家下标；`堆叠项` = **堆叠上的能力**（114.9）。
   * ⚠ 客户端的「已选」集合只认数字 `uid` —— 所以**能力的 uid 用负数 `-StackItem.id`**：
   *   既不撞实体的正 uid，也不撞玩家的 0/1。中间层原样传递，只在「列候选」和「收目标」两处转换。
   */
  类型: '实体' | '玩家' | '堆叠项';
  uid?: number; 玩家?: number; 名称: string; 敌?: boolean;
}

export interface 合法动作 {
  种类: '打领土' | '施放' | '启动能力' | '发起战斗' | '让过' | '转移';
  uid?: number;
  能力索引?: number;
  /** 700.2b：启动式能力的模式是**作为进入堆叠的一部分**选的 —— 一个模式一条动作，界面不用再问 */
  模式号?: number;
  标签: string;
  /** 打领土时打明置还是暗置（304.4a / 304.4b）—— **每条动作自己带着**，界面不用再问 */
  面?: '明置' | '暗置';
  /** 304.4b：这张牌只能暗置打出（它不是领土牌） */
  必须暗置?: boolean;
  需要阵地?: { 阵地: 阵地; 标签: string }[];
  /** 换阵地：移到哪个阵地 */
  到?: 阵地;
  /**
   * 走**哪条路**换阵地 —— 两者是不同能力，次数与目的地都不同：
   *   '转移' = 702.16 关键词（只有相邻空阵地）
   *   '许可' = 116.2c 效应授予的移动（【急行军】，你的任意空阵地）
   */
  路径?: '转移' | '许可';
 /** 费用里带 {X}（界面强制手动挑地） */
 是X?: boolean;
 /** 数字费用（手动支付时的需要额） */
 费用数?: number;
  /** 601.2f：这张牌的**额外费用**要牺牲一个单位 —— 界面拿它开槽，客户端把选中的 uid 放回 额外牺牲 */
  /** 601.2f：这个额外费用要牺牲几个（109 现在是 1） */
  额外牺牲数?: number;
  额外牺牲候选?: { uid: number; 名称: string }[];
 /** 108.3a：这个**启动式能力**的费用带 {X} —— 界面先问宣告多少，再按 X 开费用槽 */
 费用X?: boolean;
 费用步进?: { 偏移: number; 步进: number };   // X 费的可选点数形状（{X}{X} → 步进 2）
  目标规格?: { 目标名: string; 数量: { 最小: number; 最大: number }; 候选: 候选[] }[];
  /** 602.1d 的启动费用候选（界面开槽用）：弃哪几张牌 / 牺牲哪个单位 */
  费用弃牌数?: number;
  费用牺牲数?: number;
  费用弃牌?: { uid: number; 名称: string }[];
  费用牺牲?: { uid: number; 名称: string }[];
  攻击对象?: { 标签: string; 种类: '玩家' | '阵地'; 玩家: number; 阵地?: 阵地 }[];
}

/**
 * 列出这个玩家现在能做的**每一件事**，以及每件事的合法目标。界面按它生成按钮。
 * 纯查询、无副作用（界面刷新一次会调它很多次）。真正的执行在 `应用动作`。
 */

export function 列出合法动作(g: GameState, p: number, opts: 时机选项): 合法动作[] {
  const out: 合法动作[] = [];
  const me = g.players[p]!;
  // 108.9 通常时机
  const 通常时机 = opts.允许通常时机 && 处于通常时机(g, p);

  // 304.1：打出领土要「通常时机」，而通常时机要求堆叠为空（117.1b/117.1c）。
  // 所以【魏新兵】还在堆叠里时不能打领土，必须等它结算完。
  if (opts.允许打领土 && g.stack.length === 0) {
    for (const o of me.hand) {
      // ⚠ **明置和暗置各是一条**（304.4a / 304.4b），`面` 直接写在动作里。
      //   以前领土牌只给一条「打出领土」+ `可暗置: true`，把「明置还是暗置」留给界面**再问一次** ——
      //   于是领土牌要两步（打出领土 → 选明置/暗置），而非领土牌（走下面那支 + 施放）是一步列完的。
      //   同一件事两种交互，已经统一：**能打几条就给几条**，界面只管列出来。
      if (能打出领土(g, p, o, '明置')) {
        out.push({ 种类: '打领土', uid: o.uid, 面: '明置', 标签: '打出领土 ' + o.def.全名 });
      }
      // 304.4b：不是领土牌也能暗置打出，成为一个暗置领土
      if (能打出领土(g, p, o, '暗置')) {
        out.push({ 种类: '打领土', uid: o.uid, 面: '暗置', 标签: '暗置打出 ' + o.def.全名 + '（作为暗置领土）' });
      }
    }
  }

  // 换个阵地：特殊动作，不走堆叠、不给优先权（110.5）。
  // 堆叠非空时不能做（要等结算完），和打领土同一个道理。
  // ⚠ **两条路各列各的** —— 它们是两种不同的能力（116.2d 转移 / 116.2c 效应授予的移动）：
  //   次数分开算、目的地也不同（转移只有相邻，许可可以是你任意空阵地）。
  //   以前合成一条，界面上就分不出玩家想走哪条，次数也会互相吃。
  if (g.stack.length === 0) {
    // 战场是共享区域 —— 「你的」= 有效控制器是 p（613.1b 层 2 之后的）
    for (const u of g.战场) {
      if (有效控制器(g, u) !== p) continue;
      if (能转移(g, p, u)) {
        for (const 到 of 转移关键词目标(g, u)) {
          out.push({ 种类: '转移', uid: u.uid, 到, 路径: '转移', 标签: '转移 ' + u.def.全名 + ' → ' + 到 });
        }
      }
      if (能移动许可(g, p, u)) {
        for (const 到 of 许可目标(g, u)) {
          out.push({ 种类: '转移', uid: u.uid, 到, 路径: '许可', 标签: '移动 ' + u.def.全名 + ' → ' + 到 });
        }
      }
    }
  }

  for (const o of me.hand) {
    if (o.def.类别.includes('领土')) continue;
    if (!能施放(g, p, o).ok) continue;
    // 108.3a：费用带 X 的牌，X 由操控者打出时宣告（最小 0），所以按 0 判它能不能打
    const 是X = 牌面费用值(o.def.打出费用) === 'X';
    // 604：**实际费用**（含费用修正，例如【李典】的加价）—— 客户端照它决定要挑几块地
    if (!可支付数字费用(g, p, 是X ? 0 : 实际打出费用(g, p, o.def))) continue;
    const 目标规格: { 目标名: string; 数量: { 最小: number; 最大: number }; 候选: 候选[] }[] = [];
    let 可行 = true;
    // ⚠ **一起看**：各槽能不能同时填满（一个物件只能进一个槽）。各查各的会让
    //   129 貂蝉那种「两个槽条件一样」在只有一个合法物件时被误判成可行。
    if (!能填满所有槽(g, p, o.def.能力?.目标 ?? [])) 可行 = false;
    for (const spec of o.def.能力?.目标 ?? []) {
      // 锚 = 这个能力的来源（同一个原则：选择器要它 ✓）
      const c = 候选目标(g, p, spec, o);
      if (c.length < spec.数量.最小) { 可行 = false; break; }
      目标规格.push({
        目标名: spec.目标名, 数量: spec.数量,
        候选: c.map((x) => x.obj
          ? { 类型: '实体' as const, uid: x.obj.uid, 名称: x.obj.def.全名 }
        : x.堆叠项 !== undefined ? { 类型: '堆叠项' as const, uid: -x.堆叠项, 名称: '（能力）' }
          : { 类型: '玩家' as const, 玩家: x.玩家!, 名称: g.players[x.玩家!]!.name }),
      });
    }
    if (!可行) continue;
    // 301.9 / 初阵释疑【阵地】：**五个阵地全都能选**（不只是空阵地）——
    //   选已经有单位的阵地 = 替任它（原有单位被放逐，之后新单位进场，701.18d）。
    //   所以「没有空阵地」不再是不能打出的理由。
    let 阵地表: { 阵地: 阵地; 标签: string }[] | undefined;
    if (o.def.类别.includes('单位')) {
      const 全部 = 阵地顺序.map((s) => ({
        阵地: s,
        标签: me.阵地[s] ? s + '（替任 ' + me.阵地[s]!.def.全名 + '）' : s + '（空）',
      }));
      /**
       * 702.31 叫阵：「只要此单位的相对阵地是空阵地，对手便须优先在该阵地上打出单位令符。」
       * 702.31c：多个叫阵单位、相对阵地都空 → 对手从这些里挑一个。
       *
       * ⚠ 2026-10 修了两处 ✗→✓：
       *   ① **叫阵原先根本没被登记成关键词**（不在 `关键词解析表` 里 → `有词(...,'叫阵')` 恒 false）
       *      → 这一段从来没执行过 ✓（记录：甲 左侧翼 的骂阵兵，乙 却把单位打到右边路 ✓）；
       *   ② 原来的映射是**反的** ✗：它拿「我这里第 s 格」去对手侧找**同名格**，再镜像一次 ✓
       *      → 逼的是**我这边的同名格** ✗。正确做法是：**遍历对手的叫阵单位 → 取它所在格的相对阵地** ✓。
       */
      const 逼格 = new Set<阵地>();
      for (let i = 0; i < g.players.length; i++) {
        if (i === p) continue;                                  // 只看**对手**
        for (const 叫 of Object.values(g.players[i]!.阵地)) {
          if (!叫 || 有效控制器(g, 叫) !== i || !有词(g, 叫, '叫阵')) continue;
          const 我该格 = 相对阵地(叫.阵地);                      // ← 直接镜像「它所在的那一格」✓
          if (我该格 && !me.阵地[我该格]) 逼格.add(我该格);       // 那一格空着 → 我必须打那里 ✓
        }
      }
      const 逼 = 全部.filter(({ 阵地: s }) => 逼格.has(s));
      阵地表 = 逼.length ? 逼 : 全部;
    }
    // 601.2f：打出的额外费用同样是行为列表（109 舍生取义 = 一条 牺牲）
    const 额外牺牲费 = 取费用行为(o.def.额外费用, '牺牲');
    out.push({
      种类: '施放', uid: o.uid,
       标签: '施放 ' + o.def.全名 + '（费用 ' + (是X ? 'X' : 实际打出费用(g, p, o.def)) + '）',
      目标规格: 目标规格.length ? 目标规格 : undefined,
      需要阵地: 阵地表,
      // 108.3a：费用带 {X} 的牌，界面要问玩家宣告多少（上限 = 现在付得起的）
        是X,                                          // 界面据此决定是否强制手动挑地
      // 604：**实际费用**（含费用修正，例如【李典】的加价）——
      //   界面照它决定让玩家挑几块地，必须和引擎实际扣的一致
        // 601.2f：打出的**额外费用**（109 舍生取义「牺牲一个由你操控的单位」）——
        //   付不出就不列这张牌；付得出就把候选交给界面（和启动费用的弃牌/牺牲同一套）
        额外牺牲数: 额外牺牲费?.数量.最小,
        额外牺牲候选: 额外牺牲费
          ? 候选目标(g, p, { 目标名: '_', 数量: { 最小: 1, 最大: 9 }, 选择: { 筛选: [{ 属性: '区域', 值: '战场' }, { 属性: '种类', 值: '单位' }, { 属性: '操控者', 值: '你' }, ...(额外牺牲费.筛选 ?? [])] } }, null)
              .map((c) => ({ uid: c.obj!.uid, 名称: c.obj!.def.全名 }))
          : undefined,
       费用数: 是X ? 0 : 实际打出费用(g, p, o.def),
    });
  }

  // 506.1 / 108.9：只能在通常时机（行动阶段、非战斗流程中、堆叠为空）发起战斗
  // 602 启动式能力
  //   702.69a：再起「于具有再起能力的牌**在墓地中时**生效」—— 所以墓地也要扫
  for (const o of [...g.战场.filter((x) => 有效控制器(g, x) === p), ...me.graveyard]) {
    for (const i of 可用启动式能力(g, p, o)) {
      // 关键词能力（射击…）按 702 章展开
      const ab0 = ((o.def.能力?.能力 ?? []) as ActivatedAbility[])[i];
      const ab = ab0 ? (解析能力(ab0) as unknown as ActivatedAbility) : undefined;
      // 700.2b：模式是**作为能力进入堆叠的一部分**选的。这里按选项**展开成多条动作**
      //   （和「打领土」的明置/暗置同一个做法）—— 界面不用再多问一次「哪个模式」。
      //   徐庶（082「横置或重置一个单位」）：能力本身的 目标/效应 都是空的，全在选项里。
      type 一项 = { 模式号?: number; 目标: NonNullable<ActivatedAbility['目标']>; 标签?: string };
      const 各选项: 一项[] = ab?.模式
        ? (ab.模式.选项 as unknown as { 标签?: string; 目标?: NonNullable<ActivatedAbility['目标']> }[])
            .map((op, m) => ({ 模式号: m, 目标: op.目标 ?? [], 标签: op.标签 }))
        : [{ 模式号: undefined, 目标: ab?.目标 ?? [], 标签: ab?.标签 }];
      for (const 项 of 各选项) {
        const 规格: { 目标名: string; 数量: { 最小: number; 最大: number }; 候选: 候选[] }[] = [];
        // ⚠ 多个目标槽要**一起**判能不能填满（锚 = 能力来源）
        if (!能填满所有槽(g, p, 项.目标, o)) continue;
        // 602.1d 的启动费用（弃牌 / 牺牲）：**付不出的能力不列出来**
        // 数量 宣告X 时最小是 0（X 由启动的玩家宣告），所以不在这里卡手牌数
        const 弃牌费 = 取费用行为(ab?.费用, '弃牌');
        if (弃牌费 && !弃牌费.宣告X && g.players[p]!.hand.length < 弃牌费.数量.最小) continue;
        const 牺牲费 = 取费用行为(ab?.费用, '牺牲');
        const 可牺牲 = 牺牲费
          ? 候选目标(g, p, { 目标名: '_', 数量: { 最小: 1, 最大: 99 },
              选择: { 筛选: [{ 属性: '区域', 值: '战场' }, { 属性: '操控者', 值: '你' }, ...(牺牲费.筛选 ?? [])] } }, o)
              .map((x) => x.obj).filter((x): x is NonNullable<typeof x> => !!x)
          : [];
        if (牺牲费 && 可牺牲.length < 牺牲费.数量.最小) continue;
        for (const spec of 项.目标) {
          const c = 候选目标(g, p, spec, o);
          if (c.length < spec.数量.最小) continue;
          规格.push({ 目标名: spec.目标名, 数量: spec.数量,
            候选: c.map((x) => (x.obj ? { 类型: '实体' as const, uid: x.obj.uid, 名称: x.obj.def.全名, 敌: x.obj.操控者 !== p }
            : x.堆叠项 !== undefined ? { 类型: '堆叠项' as const, uid: -x.堆叠项, 名称: '（能力）', 敌: false }
                                    : { 类型: '玩家' as const, 玩家: x.玩家!, 名称: g.players[x.玩家!]!.name })) });
        }
        const 支付 = 支付费用(ab?.费用);
        out.push({ 种类: '启动能力', uid: o.uid, 能力索引: i, 模式号: 项.模式号,
          目标规格: 规格.length ? 规格 : undefined,
          // 数字费用（605）：界面拿它决定要不要先让玩家挑地付钱（现在**没有自动支付**了）
          费用数: 支付.宣告X ? 0 : 支付.点数,
          // 108.3a：费用带 {X} 的**启动式能力** —— 界面先问 X，再按 X 开弃牌槽
          费用X: 支付.宣告X ? true : undefined,
  // ★ 步进：X 费的"可选点数"必须落在 偏移 + n×步进（周瑜 {X}{X} → 步进 2，只能付 2/4/6 ✓）
  费用步进: 支付.宣告X ? 费用点数形状(取费用行为(ab?.费用, '支付')?.点数) : undefined,
          // 启动费用的候选（界面拿它开槽，玩家点手牌/点单位来付）—— 和施放的 支付源/阵地 同一套
          费用弃牌数: 弃牌费 ? (弃牌费.宣告X ? undefined : 弃牌费.数量.最小) : undefined,   // 宣告X → 由客户端按宣告的 X 填
          费用牺牲数: 牺牲费?.数量.最小,
          费用弃牌: 弃牌费 ? g.players[p]!.hand.slice(0, 30).map((c) => ({ uid: c.uid, 名称: c.def.全名 })) : undefined,
          费用牺牲: 牺牲费 ? 可牺牲.map((x) => ({ uid: x.uid, 名称: x.def.全名 })) : undefined,
          标签: '启动 ' + o.def.全名 + (项.标签 ? '：' + 项.标签 : '')
            + (支付.宣告X ? '（付 X 费）' : (支付.点数 > 0 ? '（付 ' + 支付.点数 + ' 费）' : '')) });
      }
    }
  }
  for (const u of 通常时机 ? g.战场.filter((x) => 有效控制器(g, x) === p) : []) {
    if (!能发起战斗(g, p, u)) continue;
    out.push({
      种类: '发起战斗', uid: u.uid, 标签: '令 ' + u.def.全名 + ' 发起战斗',
      攻击对象: 合法攻击对象(g, p, u).map((t) => t.种类 === '玩家'
        ? { 标签: '攻击 ' + g.players[t.玩家]!.name, 种类: '玩家' as const, 玩家: t.玩家 }
        : { 标签: '攻击 ' + t.阵地, 种类: '阵地' as const, 玩家: t.玩家, 阵地: t.阵地 }),
    });
  }

  out.push({ 种类: '让过', 标签: '让过' });
  return out;
}
