/** 阵地几何（403.5c） */
export const 阵地序号: Record<阵地, number> = {
  左边路: 0, 左侧翼: 1, 中路: 2, 右侧翼: 3, 右边路: 4,
};
/**
 * 403.5c：**相对阵地** —— 就按**所见的位置**对应：甲 的左边路对乙 的左边路，中路对中路，依此类推。
 * 所以它就是恒等函数：阵地名两边共用，不需要做坐标变换。
 * （规则书没有「同列 / 镜像」这两种读法的区别，之前把它做成可切换是多余的。）
 *
 * ⚠ **`null` 是合法输入**：阵地外的单位（阵略、领土、被 301.8 移出阵地的单位）
 *   **没有相对阵地**。这不是「涉及阵地的能力无效」那条规则，而是**「没有这个地方」这个事实**
 *   让那些能力自然不触发（例：迎击找不到相对阵地）。所以返回类型也是 `阵地 | null`。
 */
/**
 * **相对阵地**：「对面玩家**同名**的那个阵地」。
 *
 * ⚠ 函数体是 `return s`，看着像没写完 —— **它就该是这样**：
 *   阵地名是两边**共用**的一组（`阵地顺序`），每个玩家各有一份自己的 `阵地[名字]`，
 *   所以「乙的右侧翼」的相对阵地就是「甲的右侧翼」，取名字即可，不必做镜像换算。
 *   403.5c 的 相邻 / 斜对 也是在**同一组名字**上按序号算的（见 相邻阵地 那里的说明）。
 */
/**
 * **相对阵地 = 左右镜像**（两名玩家面对面而坐，各自从左到右命名 ✓）：
 *     左边路 ↔ 右边路　左侧翼 ↔ 右侧翼　中路 ↔ 中路
 * ⚠ 以前这里是 `return s`（同名即相对）✗ —— 那等于把两排**并排**摆，
 *   会让 508.2e 的攻击对象、702.13b 迎击、702.19b 奇袭、702.31b 叫阵 全部差一格。
 */
const 镜像阵地: Record<阵地, 阵地> = {
  左边路: '右边路', 左侧翼: '右侧翼', 中路: '中路', 右侧翼: '左侧翼', 右边路: '左边路',
};
export function 相对阵地(s: 阵地 | null): 阵地 | null { return s == null ? null : 镜像阵地[s]; }
/**
 * 403.5c：同一玩家阵地上，**左右相邻**的阵地（左边路↔左侧翼↔中路↔右侧翼↔右边路）。
 * **没有阵地 → 没有相邻阵地**（返回空数组）。
 *
 * ⚠ **它和 `斜对阵地` 不是一回事** ✗（以前这里写着"函数体一模一样，那是对的" ✗ —— 那句是错的 ✓）：
 *   相邻是**我自己这一侧**的左右两格 ✓；斜对是**对面那一侧**的两格 ✓（= 先镜像再取相邻 ✓）。
 */
export function 相邻阵地(s: 阵地 | null): 阵地[] {
  if (s === null) return [];
  const i = 阵地序号[s];
  return [阵地顺序[i - 1], 阵地顺序[i + 1]].filter((x): x is 阵地 => x !== undefined);
}
/**
 * 403.5c：**斜对阵地** —— **对面一方**斜向相邻的阵地。**没有阵地 → 空数组**。
 *
 * ⚠ **必须先镜像** ✗→✓：斜对是「**对面**斜着的那两格」✓ ——
 *   先 `镜像阵地[s]`（= `相对阵地(s)` ✓，就是「对面正对着我这一格的那格」✓），
 *   再取**对面那一侧**里它的左右相邻 ✓。
 *   以前直接取「**我自己这格**的左右邻」✗ = 镜像错位 ✓（2026-10 报的"斜对识别不正确（镜像）" ✓）。
 * ⚠ 调用方一律写成 `斜对阵地(锚.阵地).map((x) => 敌.阵地[x])` ✓（在**对面那侧**取格 ✓）——
 *   所以本函数返回的必须是**对面那一侧的名字** ✓。
 */
export function 斜对阵地(s: 阵地 | null): 阵地[] {
  if (s === null) return [];
  const 对面 = 镜像阵地[s];                      // ← 先镜像 ✓（这一步以前漏了 ✗）
  const i = 阵地序号[对面];
  return [阵地顺序[i - 1], 阵地顺序[i + 1]].filter((x): x is 阵地 => x !== undefined);
}

