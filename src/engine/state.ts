/**
 * 持续性效应（610/611）的**载荷** —— 一个持续性效应是「持续一段时间、作用在某范围内」的
 * 东西，载荷决定它**在什么时候、以什么方式**生效：
 *   · 层   —— 613 层系统：改**特征**（武力 / 类别 / 关键词…），在算特征时生效；
 *   · 替代 —— 614 / 615：改**事件**（伤害的防止与替代），在事件发生时生效。
 *
 * ⚠ 以前这里只有 `层: 层修改` 而且**必填**，于是「持续到回合结束的防止伤害」根本写不出来 ——
 *   041 主将的鼓舞 / 046 奋迅 / 097 小乔 / 解烦营 四张牌因此一直录不进去。
 *   做成联合之后，两类持续性效应共用**同一个记录、同一套时长管理、同一个来源**。
 *
 * ⚠⚠ **两样可以同时带** —— 613.6：一个效应可以横跨多层、做不止一件事。
 *   046 奋迅就是「+3 武力 **且** 防止 3 点伤害」，那是**一个效应的两个部分**，
 *   不该拆成两条 持续。消费端各取所需：层系统只看 层，伤害管线只看 替代。
 */
export interface 连续载荷 {
  /** 613 层系统：改**特征**（武力 / 类别 / 关键词…），在算特征时生效 */
  层?: 层修改;
  /** 614 / 615：改**事件**（伤害的防止与替代），在事件发生时生效 */
  替代?: ReplacementSpec;
}

