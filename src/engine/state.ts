/* ── 写入的唯一入口 ──────────────────────────────────────────────
   ⚠ 影响派生数据（候选表 / 无能力集合 / 特征 / 有效控制器）的字段在 `GameState`/`Obj` 上全是
     `readonly` ✓ → 别处**写不了**（`tsc` 直接报错 ✓），只能走下面这些 mutator ✓；
     每个 mutator 结尾都 `盖章(g)`（状态版本 +1 ✓），派生缓存按它作废 ✓。
   ⚠ 这条链的目标是把失败模式从「实战里静默算错」✗ 变成「编译不过 / 测试红」✓：
     上次（`3a82baa`）靠人手写 15 处 `盖章`，结果 `tempEffects`（`continuous.ts:243` 明确读它 ✓）
     与 `阵地`（同袍读邻居阵地 ✓）都漏了 ✗ —— 类型锁死就是为了让这种漏**不可能发生** ✓。
   ⚠ `记忆` 是 `Record` → 编译器抓不到 `o.记忆[k] = v` ✗ → 一律走 `写记忆` ✓。 */

/** 可写视图 —— **只在 state.ts 内部用** ✓（别处拿到的是 readonly 类型 ✓） */
type 可写<T> = { -readonly [K in keyof T]: T[K] };
const 写 = <T>(x: T): 可写<T> => x as 可写<T>;
/** 只读数组 → 可写数组（**只在 state.ts 内部用** ✓） */
const 表 = <T>(x: readonly T[]): T[] => x as T[];

/** ⚠ **盖章：状态变了** —— 会影响派生结果的写入之后都调它 ✓（下面每个 mutator 都调 ✓） */
