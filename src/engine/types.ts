/**
 * 系列 + 编号 合成的**唯一卡号**，同时也是卡图文件名（**全大写**）。
 * 大小写混用会埋坑（URL 大小写敏感、换到 Linux 上 cz-179 和 CZ-179 是两个文件），
 * 所以这里统一 toUpperCase()，卡图文件也必须用大写名。
 */
export function 卡号(c: { 系列: string; 编号: string }): string {
  return c.系列.toUpperCase() + '-' + c.编号;
}

/**
 * 卡图路径的约定：**按系列分目录** —— `/cards/<系列>/<系列>-<编号>.jpg`（**原样，不编码**）。
 *
 * ⚠ 这里**不能 encodeURIComponent** —— 返回值有两个用处：
 *   ① 给浏览器当 URL（浏览器自己会编码，服务端再 decode 回来）
 *   ② 给服务端 `有卡图()` 拼 `'web' + 卡图(c)` 当**文件系统路径**查存在性
 *   一旦编码了，② 就指向 `web/cards/%E5%88%9D%E9%98%B5/...` 这个不存在的目录 —— 卡图全变 null。
 */
export function 卡图(c: { 系列: string; 编号: string }): string {
  return '/cards/' + c.系列 + '/' + 卡号(c) + '.jpg';
}

