export interface Trigger {
  /**
   * ⚠ **直接用 事件名** —— 以前这里另抄了一份联合，于是往 事件名 加了新事件（'回复体力'）
   *   之后，触发这边仍然编译不过，而且两边会慢慢漂开。唯一的清单只该有一份。
   */
  事件: 事件名;
  /**
   * 触发的主语是谁 —— **和这个来源的关系**，只有三种**关系**用字面量：
   *   · `'自身'` —— 「当**此物**…」（默认）
   *   · `'所附属'` / `'所佩带'` —— 「当**所附属/所佩带**的那个单位…」（089 / 178）
   *   （这两个判的是 来源.附属在 / 来源.佩带在，见 Selector 的同名字段。）
   *
   * **其余一律写成选择器** ✓ —— 和 `目标.选择` / `持续.范围` 同一个类型、同一套词汇，
   * 引擎用同一个 `符合选择器` 判「受体是不是满足这个选择器」：
   *   · 「当**另一个单位**死去时」            = `{ 种类:'单位' }`（156 亡国哀民）
   *   · 「当**一个由你操控的单位**移动时」   = `{ 种类:'单位', 操控者:'你' }`（124 公孙瓒）
   *   · 「当**一个领土在你的操控下**进场时」 = `{ 种类:'领土', 操控者:'你' }`（036 于禁）
   *   · 「当**任一玩家**回复体力时」         = `{}`（058 仁者的大德 —— 受方是玩家号，没有物件特征可筛）
   *
   * ⚠ 两条语义要点：
   *   · **「另一个」由数据里的 `除:'自身'` 表达** ✓ —— 主体 只要不是 `'自身'`，本来就是「另一个」：
   *     匹配时引擎会补 `除:'自身'`（排除**这个能力所在的来源**，锚 = 来源），**数据不写** ✓；
   *   · `操控者:'你'` = **和触发器同一个操控者**（按 613.1b 生效后的操控权算），
   *     不是「玩家的你」—— 所以「由你操控的」也落在选择器里，不再另开字段。
   */
  主体?: '自身' | '所附属' | '所佩带' | Selector;
  /**
   * 触发这件事的**受方是哪一类**（不写 = 两类都算）：
   *   · `'玩家'` —— 例：058 仁者的大德「当**任一玩家**回复体力时」；
   *     033 徐晃「当徐晃对**玩家**造成伤害时」。
   *   · `'实体'` —— 例：058 另一条「当**一个单位**回复体力时」。
   *
   * ⚠ 这是**通用**判据，不是给某张牌开的字段：伤害、回复、抓牌等事件的受方本来就分
   *   「玩家」和「实体」两类（和 SelectKind 里的 玩家 / 实体 同一套区分）。
   *   033 徐晃原来用的 `对玩家?: boolean` 就是这条的一个特例，已并过来。
   */
  受方?: '玩家' | '实体';
  /**
   * **判来源**的筛选（不写 = 不判来源）。
   *
   * ⚠ `筛选` 判的是「那个**受方**物件」，这一条判的是「**来源**物件」——
   *   048 关平「当关平成为**锦囊令符或阵略令符**的目标时」要判的是那个令符，不是关平自己。
   */
  筛选来源?: 筛选;
  步骤?: '重置步骤' | '准备步骤' | '抓牌步骤' | '结束步骤' | '弃牌步骤';
  阶段?: '开始阶段' | '行动阶段' | '收官阶段';
  谁的回合?: '你' | '任意';
  /**
   * **只对「符合条件的那个物件」触发**（不是「来源符合」）。
   * 例：036 于禁「每当一个**领土**在你的操控下进战场时…」——
   *   `{ 事件:'进战场', 筛选:[{ 属性:'类别', 值:'领土' }] }`
   *   「在你的操控下」由引擎按 603.2g 对进场物件的操控者判定。
   */
  筛选?: 筛选条件[];
 /**
  * 「当…，**若**…，…」里的那个「若」（释疑·有条件的触发式能力）：
  *   · 在**触发时**判 —— 不成立就不触发（不进 g.pending，也不问玩家选目标）；
  *   · 结算时不成立时，效应自己做不了事，自然空过，不需要在堆叠项上再存一份条件。
  * 判定的「你」= 这个能力来源的**有效操控者**（613.1b）。
  */
 条件?: Condition;
}

