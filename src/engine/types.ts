/**
 * **历史条件** —— 这个实体**过去发生过什么**。
 *
 * 和「牌面特征筛选」是**两条不同的轴**：
 *   牌面特征（类别/势力/武力…）查 Obj.def + 层系统算出的特征；
 *   历史条件查**引擎的事件记录**。
 * 两者可以并存（都是「且」）。
 *
 * ⚠ **不要把它做成「一个条件一个枚举值」** —— 那是整句封装，会组合爆炸。
 *   拆成 事件 × 角色 × 时段 × 数量 四个部件，N 个说法只需 4 个部件。
 *
 * 例：「本回合受到过伤害的单位」= { 事件:'受到伤害', 角色:'受方', 时段:'本回合' }
 */
export interface 历史条件 {
  事件: 事件名;
  /** 它在这个事件里的角色。省略 = 哪边都算 */
  角色?: '来源' | '受方';
  /** 省略 = 这盘游戏以来 */
  时段?: '本回合' | '上回合' | '本步骤' | '这盘游戏';
  /** 「受到过 3 点以上伤害」这种。省略 = 发生过就算 */
  数量?: { 比较: 筛选比较; 值: number };
}

