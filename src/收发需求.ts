/**
 * **收发层的「选择需求」** —— 把引擎/状态已经算好的东西打包成客户端能直接吃的形状 ✓
 *
 * 目标：**客户端不翻译**。客户端只认三件事：
 *   ① `槽.候选[i].键` —— 呈现用（高亮 / 点击 / 名额）；
 *      `槽.候选[i].发` —— 这个候选回传时**变成什么**（省略 = 键本身）✓
 *   ② 模板里的 `'$归名'` —— 把所有 `归` 等于该名字的槽的已选**拼成一个数组**（`发` 逐项展开）✓
 *   ③ 模板里的 `'@字段'` —— 动作/决定**自身**的字段；其余是字面量 ✓
 *
 * 需求 = {
 *   标题: '打出 魏武精兵（费用 1）',
 *   槽: [ { 名:'阵地', 归:'阵地', 需:{最小:1,最大:1},
 *          候选:[{键:'左边路', 发:'左边路'}], 条件:{玩家:0} },
 *         { 名:'支付源', 归:'支付源', 需:{最小:1,最大:1}, 候选:[{键:地uid, 发:地uid}] } ],
 *   确认后发: { 种类:'打出', uid:'@uid', 目标:'$目标', 阵地:'$阵地', 支付源:'$支付源' },
 *   放弃后发?: { 种类:'决定', 接受:false },     // 「未搜寻到」这类分支（701.17b）
 * }
 *
 * ⚠ **一切从槽来的值都是数组** ✓ —— 包括 `阵地` / `先手` / `张数` / `接受` 这些「逻辑上单值」的字段：
 *   收窄成引擎要的形状是**解析动作**的事（那边按字段 `取首` ✓）。
 *   客户端因此**永远不需要**「这一槽要几个」这种猜测 ✗ ——
 *   那正是「按名额猜形状 → 单选的决定发了标量 → 引擎静默丢掉选择 → 日志『X 选了（没有）』」的成因 ✓。
 *
 * ⚠ **阵地只有一种表示**（一个键列表）✓：选阵地走 `决定.选`（数组）、打出阵地走 `打出.阵地`
 *   （也是数组，解析动作取首）✓ —— 同一个概念不再有两种 wire 形状 ✓。
 */
