/** 一个候选项：`键` 给界面（高亮/点击/名额）、`名` 给界面（文字）、`发` 给引擎（省略 = 键本身）、
 *  `量` = 这个候选算多少（缺省 1，领土写「提供」）✓
 *  `区` = 它现在在哪个区域 ✓ —— 服务端给，客户端不猜 ✓；⚠ **没有 `名` 就是背面** ✓（服务端不给牌面）*/
type 候选项 = { 键: number | string; 名?: string; 发?: unknown; 量?: number; 区?: string; 可选?: boolean;
  /** 依赖X（095）：这个候选要求的宣告 X（= 它的费用值）；客户端按已选 X 过滤 */
  需X?: number };
/**
 * 一个槽 = 这次要选的一样东西。
 * `归` 是**它填进模板的哪个字段**（同名字段 = 同一组，提交时按槽顺序拼成一个数组 ✓）。
 * `呈现:'按钮'` = **这些候选不在场上**（座位号 / 张数 / 是否发动）→ 面板把它们画成按钮 ✓；
 *   省略 = 候选在场上/手牌上，玩家点那些东西 ✓（客户端不猜哪个键在屏幕上能点 ✗）。
 * `候选.量` = 这个候选算**多少「量」**（缺省 1）✓ —— 领土的「提供」就在这里：
 *   于是「要付 2 点」是按**点数**卡确认 ✓，而不是按**张数** ✗（一张提供 2 的地就够 ✓ 304.8）。
 */
type 槽 = {
  名: string;
  归: string;
  /** 目标规格上写的提示文字（`TargetSpec.标签`）——界面上代替槽名显示 */
  提示?: string;
  需: { 最小: number; 最大: number; 步进?: number };   // 步进：选中量必须 = 最小 + n×步进（缺省 1 = 连续区间）
  候选: 候选项[];
  条件?: { 玩家: number };
  呈现?: '按钮';
  /**
   * ⚠ **这个槽里的候选是"可以查看的牌"** ✓ —— 由**服务端**说 ✓（客户端不猜 ✗）：
   *   面板据此给一个「查看（N 张）」入口 ✓（点开是玩家自己的查看容器 ✓）。
   * 为什么必须由服务端说 ✗→✓：这原来是靠 `已检视` 那张表"有没有内容"隐式表达的 ✓，
   *   界面改成"只画当前需求"之后信号丢了 ✗ → 客户端只能猜"候选有没有牌面/是不是隐藏区" ✗
   *   → 猜漏（该有按钮时没有 ✓）猜宽（无关步骤冒出来 ✓）两头都错 ✓。
   */
  可查看?: boolean;
  /**
   * **依赖前一个目标槽**（050 螺旋突刺的第二个目标）：
   *   `槽` = 锚槽名，`映射` = 锚候选键 → 本槽可选键。客户端只让点配对内的候选。
   */
  按锚?: { 槽: string; 映射: Record<string, (number | string)[]> };
  /** 本槽候选的该属性必须等于本牌宣告的 X（095）；候选带 `需X` */
  按X?: string;
};
export interface 需求 {
  /** ⚠ **这次让你看的牌**（服务器给的、只读 ✓）—— 界面的「查看」按钮点开就是它 ✓ */
  查看?: 候选项[];
  标题: string;
  槽: 槽[];
  确认后发: Record<string, unknown>;
  /** 「未搜寻到」这类**放弃**分支的模板 —— 由服务端给，客户端不拼 ✓ */
  放弃后发?: Record<string, unknown>;
  /** 放弃按钮的**文字**（701.17b「未搜寻到」/ 开局「随机」）—— 同样由服务端给 ✓ */
  放弃名?: string;

}

/**
 * **uid → 它现在在哪个区域**（面板要按区域分组、并决定画正面还是背面 ✓）
 * ⚠ 规则：**候选没有 `名` 就是背面** ✓（服务端不给牌面 = 你看不到 ✓，客户端不猜 ✗）。
 */
const 区of = (g: GameState | undefined, uid: number): string | undefined => {
  if (!g || !Array.isArray(g.战场)) return undefined;
  for (const p of g.players) {
    if ((p.hand ?? []).some((c) => c.uid === uid)) return '手牌';
    if ((p.graveyard ?? []).some((c) => c.uid === uid)) return '墓地';
    if ((p.library ?? []).some((c) => c.uid === uid)) return '牌库';
  }
  if (g.战场.some((c) => c.uid === uid)) return '战场';
  if ((g.放逐区 ?? []).some((c) => c.uid === uid)) return '放逐区';
  if ((g.stack ?? []).some((s) => s.card && s.card.uid === uid)) return '堆叠';
  return undefined;
};

/**
 * 候选 → 键（界面里的「键」只有两套：物件 uid、玩家 `'玩家'+座位`）✓
 * ⚠ 玩家那一条**必须有** ✗ —— 漏了会落到 `名称`，键变成玩家名字 `'甲'` ✓
 *   → 点目标玩家时不在候选里 ✓ → **点了没反应** ✓（2026-02 报的 ✓）。
 */
const 键候选项 = (xs: unknown[] | undefined, g?: GameState): 候选项[] => (xs || []).map((x) => {
  if (typeof x === 'number' || typeof x === 'string') {
    return typeof x === 'number' ? { 键: x, ...(区of(g, x) ? { 区: 区of(g, x)! } : {}) } : { 键: x };
  }
  const o = x as Record<string, unknown>;
  const 名 = typeof o.名称 === 'string' ? o.名称 : undefined;
  /** ⚠ 候选**自带的 `区` 优先** ✓ —— 引擎/决定已经声明了区域就照用 ✓；
   *  没声明才由服务端按 uid 查表 ✓（两种来源都支持 ✓，测试/桩也能直接给 ✓）。 */
  const 源区 = typeof o.区 === 'string' ? o.区 : undefined;
  /** ⚠ 候选**自带的牌面**（`卡`）也透传 ✓ —— 服务端富化过的那一步（`挂牌面` ✓）、
   *  以及测试/桩直接给的，都照用 ✓；没有就不带 ✓（面板就画「背面」小按钮 ✓）。 */
  const 源卡 = o.卡 as unknown;
  const 带名 = (c: 候选项): 候选项 => (名 ? { ...c, 名 } : c);
  const 带区 = (键: number | string): 候选项 => {
    const k = typeof 键 === 'number' ? 键 : (typeof o.uid === 'number' ? o.uid : undefined);
    const 区 = 源区 ?? (k !== undefined ? 区of(g, k) : undefined);
    return { 键, ...(区 ? { 区 } : {}), ...(源卡 !== undefined ? { 卡: 源卡 } : {}), ...(typeof o.可选 === 'boolean' ? { 可选: o.可选 } : {}) };
  };
  if (typeof o.uid === 'number') return 带名(带区(o.uid));
  if (typeof o.玩家 === 'number') return 带名({ 键: '玩家' + o.玩家 });
  if (typeof o.键 === 'string' || typeof o.键 === 'number') return 带名(带区(o.键 as number | string));
  if (typeof o.阵地 === 'string') return 带名({ 键: o.阵地 });
  if (名) return { 键: 名, 名 };
  return { 键: String(o.键 ?? '') };
});

/**
 * **目标候选**：键沿用老约定（uid / `'玩家'+座位`）✓ —— 棋盘高亮与查看器点选都用它；
 * `发` = 引擎要的目标对象（**带 `目标名`** ✓ —— `宣告` 的 wire 就按 `目标名` 分组，
 * 而 `打出` / `启动能力` 只读 `类型`/`uid`/`玩家`，多一个字段不碍事 ✓）。
 */
const 目标候选项 = (xs: unknown[] | undefined, 目标名: string, g?: GameState): 候选项[] =>
  (xs || []).map((x) => {
    const c = (x || {}) as { 类型?: string; uid?: number; 玩家?: number; 名称?: string; 需X?: number };
    const 名 = typeof c.名称 === 'string' ? c.名称 : undefined;
    if (c.类型 === '玩家' && typeof c.玩家 === 'number') {
      return { 键: '玩家' + c.玩家, ...(名 ? { 名 } : {}), 发: { 目标名, 类型: '玩家', 玩家: c.玩家 } };
    }
    if (typeof c.uid === 'number') {
      const 区 = 区of(g, c.uid);
      return { 键: c.uid, ...(名 ? { 名 } : {}), ...(区 ? { 区 } : {}), ...(typeof c.需X === 'number' ? { 需X: c.需X } : {}), 发: { 目标名, 类型: c.类型 ?? '实体', uid: c.uid } };
    }
    return { 键: String(名 ?? ''), ...(名 ? { 名 } : {}), 发: { 目标名, 类型: c.类型, 名称: c.名称 } };
  });

/**
 * **支付候选**：`量` = 这块领土能提供几点 ✓（304.8 / 118.2 —— 一张提供 2 的地就够付 2 点）。
 * 收 `可支付来源()` 的原对象（`{uid, 提供}`），也接受裸 uid/字符串 ✓。
 */
const 支付候选项 = (xs: unknown[] | undefined): 候选项[] => (xs || []).map((x) => {
  const o = (x && typeof x === 'object') ? x as { uid?: number; 提供?: number } : undefined;
  if (o && typeof o.uid === 'number') {
    return { 键: o.uid, ...(typeof o.提供 === 'number' && o.提供 !== 1 ? { 量: o.提供 } : {}) };
  }
  return { 键: x as number | string };
});

/** 座位候选（103.1）：名字从状态里取，界面直接画按钮 ✓ */const 座位候选项 = (xs: number[] | undefined, g?: GameState): 候选项[] =>
  (xs || []).map((i) => ({ 键: i, 发: i, 名: (g?.players[i]?.name ?? String(i)) + ' 先手' }));

/** 张数候选（103.4 宣告）：0 的措辞由服务端给 ✓（客户端不认识「0 = 不调度」这种语义 ✗） */
const 张数候选项 = (xs: number[] | undefined): 候选项[] =>
  (xs || []).map((k) => ({ 键: k, 发: k, 名: k === 0 ? '不调度' : k + ' 张' }));

/** 「数量」在引擎里有时是数字（`2`）、有时是 `{最小,最大}` —— 统一成后者 ✓ */
const 名额 = (v: unknown, 缺省: number): { 最小: number; 最大: number } => {
  if (typeof v === 'number') return { 最小: v, 最大: v };
  const o = v as { 最小?: number; 最大?: number } | undefined;
  if (o && typeof o.最小 === 'number' && typeof o.最大 === 'number') return { 最小: o.最小, 最大: o.最大 };
  return { 最小: 缺省, 最大: 缺省 };
};

/** 目标规格（`a.目标规格` / `决定.规格` / `决定.槽`）→ 每规格一个槽，**全归 `目标`** ✓ */
const 规格槽s = (规格: unknown, 条件: { 玩家: number }, g?: GameState): 槽[] =>
  ((规格 as { 目标名: string; 数量?: unknown; 候选?: unknown[]; 标签?: string; 依赖?: string; 按锚?: Record<string, (number | string)[]>; 按X?: string }[] | undefined) || []).map((sp) => ({
    名: sp.目标名,
    归: '目标',
    ...(sp.标签 ? { 提示: sp.标签 } : {}),
    需: 名额(sp.数量, 1),
    候选: 目标候选项(sp.候选, sp.目标名, g),
    条件,
    ...(sp.依赖 && sp.按锚 ? { 按锚: { 槽: sp.依赖, 映射: sp.按锚 } } : {}),
    ...(sp.按X ? { 按X: sp.按X } : {}),
  }));

