/** 当前请求的「决定」→ 需求 ✓（`g` / `座位` 只为「弃牌」这种候选在引擎手里的决定准备 ✓） */
/**
 * **「支付源」槽的唯一构造点** ✓ —— 打出/启动式（`费`）、攻击税（`0..税`）、效应里的可选支付 都该走这里 ✓。
 * ⚠ 2026-10 以前是**三份手写字面量** ✗（字段还不完全一样 ✗）→ 每次"付钱"都要重新对一遍 ✓。
 * `候选` 用 `支付候选项()` 的产物（`{键, 名, 量}` ✓，`量` = 它提供几点 ✓）。
 */
function 支付源槽(候选: 候选项[], 最小: number, 最大: number, 条件?: unknown, 步进?: number): 槽 {
  return { 名: '支付源', 归: '支付源', 需: { 最小, 最大, ...(步进 && 步进 > 1 ? { 步进 } : {}) }, 候选, ...(条件 ? { 条件 } : {}) } as 槽;
}
export function 需求_决定(d: Record<string, unknown>, g?: GameState, 座位 = 0): 需求 | null {
  const 类型 = String(d.类型 || '');
  const 标题 = String(d.标签 || '');
  const 谁 = typeof d.玩家 === 'number' ? d.玩家 : 座位;
  const 条件 = { 玩家: 谁 };
// ── 查看（纯展示：只有「查看」内容 + 一个确认，没有槽）──────────
if (类型 === '查看') {
  const 看 = 键候选项((d.查看 as unknown[] | undefined) ?? [], g);
  if (!看.length) return null;
  return { 标题: 标题 || '查看',
    槽: [], 查看: 看,
    确认后发: { 种类: '决定', 接受: true, 选: [] } };
}
// ── 触发式能力的「你可以…」一问（可选触发）───────────────────────
if (类型 === '可选触发') {
  return { 标题,
    槽: [{ 名: '是否发动', 归: '接受', 需: { 最小: 1, 最大: 1 }, 呈现: '按钮',
      候选: [{ 键: '发动', 名: '发动', 发: true }, { 键: '不发动', 名: '不发动', 发: false }] }],
    确认后发: { 种类: '决定', 接受: '$接受' } };
}
// ── 514 弃牌（候选在引擎手里 → 靠 `g`）───────────────────────────
if (类型 === '弃牌') {
  const n = (d.需弃 as number) || 0;
  const 手 = g ? (g.players[谁]?.hand ?? []) : [];
  return { 标题: 标题 || '弃 ' + n + ' 张牌',
    槽: [{ 名: '弃牌', 归: '弃牌', 需: { 最小: n, 最大: n },
      候选: 手.map((c) => ({ 键: c.uid, 名: c.def?.全名 ?? String(c.uid) })) }],
    确认后发: { 种类: '决定', 接受: true, 弃牌: '$弃牌' } };
}
// ── 701.17 搜寻（可放弃 = 「未搜寻到」，701.17b）────────────
if (类型 === '搜寻') {
  const n = typeof d.数量 === 'number' ? d.数量 : 1;
    const 候选 = (d.候选 as { uid: number; 名称?: string; 可选?: boolean; 区?: string; 卡?: unknown }[] | undefined) || [];
    const 可放弃 = d.可放弃 === true;
    // ⚠ **查看内容放在【需求】这一层** ✓（不是槽里 ✗）—— 界面读的是 `需求.查看` ✓
    //   （放槽里 = 界面读不到 ✓ → 不画「查看」按钮 ✗；而面板又不列候选 ✗ → 整步**看起来是空的** ✓ ——
    //    2026-10 用户报的"郭嘉搜寻牌库显示为空" ✓ 就是这个：牌都发了 ✓，但没有入口 ✓）。
    const 候选2 = 键候选项(候选, g);
    const 看 = 查看内容(d, 候选2, g);      // ← 判定只有一处 ✓（见 查看内容() 的说明 ✓）
    return { 标题,
      // ⚠ 走 `键候选项`（**不是**自己 map）✓ —— 这样候选自带的 `区` / 牌面 `卡` 才透传得下去 ✓
      槽: [{ 名: '选', 归: '选', 需: { 最小: 可放弃 ? 0 : n, 最大: n },
        候选: 候选2 }],
      ...(看.length ? { 查看: 看 } : {}),
      确认后发: { 种类: '决定', 接受: true, 选: '$选' },
      ...(可放弃 ? { 放弃后发: { 种类: '决定', 接受: false }, 放弃名: '未搜寻到' } : {}) };
  }
  // ── 宣告（触发式能力：先选模式，再选各槽目标）─────────────────────
  if (类型 === '宣告') {
    /**
     * ⚠ **两段式**（700.2b / 603.3c ✓，用户口径 ✓）：
     *   · **第一段：选模式** —— 只发模式槽 ✓（候选带名字 ✓；引擎给的本来就是按 603.3c 剔过的**合法模式** ✓，
     *     所以界面上不会出现"点了没用的模式" ✓）。
     *     模板**只要模式** ✗、**不带 `目标`** —— 此刻还不知道这个模式要选什么 ✓。
     *     以前这里硬塞 `目标:'$目标'` ✗ → 客户端填不上 → **确认永远按不动** ✓（2026-10 报的 ✓）。
 *   · **第二段：该模式的目标** —— 模式在「进堆叠」时定（700.2b），**目标同一时点**问（603.3d）：
 *     引擎在放堆叠的生成器里紧接着再发一份 宣告（带该模式的 规格）→ 这里走 规格槽s，两问都在对手响应之前。
     */
    const 模式候选 = (d.模式候选 as { 索引: number; 标签?: string }[] | undefined) || [];
    if (模式候选.length) {
      return { 标题,
        // ⚠ **必须标 `呈现: '按钮'`** ✓ —— 模式候选**不在棋盘上**（不像目标/阵地那样能在场上点 ✓），
        //   而面板默认**不列候选** ✗（候选一律在棋盘 / 查看容器里点 ✓）→ 不标就"没有东西可点" ✓
        //   （确认按不动 ✓ 2026-10 报的 ✓）。和「选项」那一类同一个字段 ✓。
        槽: [{ 名: '模式', 归: '模式', 需: { 最小: 1, 最大: 1 }, 呈现: '按钮',
          候选: 模式候选.map((m) => ({ 键: String(m.索引), ...(m.标签 ? { 名: m.标签 } : {}), 发: m.索引 })) }],
        确认后发: { 种类: '宣告', 模式: '$模式' } };
    }
    return { 标题, 槽: 规格槽s(d.规格 as unknown, 条件, g),
      确认后发: { 种类: '宣告', 目标: '$目标' } };
  }
  // ── 统一【选】：选物件 / 选项 / 阵地 / 触发（可带多槽）────────────
  if (类型 === '选') {
    // ⚠ **哪些选的候选在场上、哪些不在** —— 由这里声明 ✓（客户端不猜 ✗）：
    //   · 物件 / 阵地 → 在场上（棋盘上点 ✓）
    //   · 触发 → 在堆叠区那一条里点 ✓（`当前任务` 把候选名单交给堆叠行 ✓）
    //   · **选项 → 场上什么都没有**（引擎给的是 `{键:'接受',名称:'支付 3 点'}` 这种 ✓，
    //      108.3a 的「要不要付这笔钱」）→ **必须由面板画按钮** ✓
    //      ⚠ 漏了它 = 选项那一步只显示进度条、点不了 ✗（和「看牌库顶」同一类 ✗）
    /**
     * ⚠ **支付源那一问**（黄月英「你可以支付{N}」✓）→ 用**现成的支付源槽** ✓：
     *   `归:'支付源'` ✓ + `需` 按**点数** ✓ + 候选带 `提供` ✓ → 客户端零改动就是"支付 0/1 + 点领土" ✓
     *   （打出/启动式用的同一套 ✓）；模板把已选的 uid 放进 `选` ✓ —— 普通"决定"答复 ✓
     *   → 服务端写 `本次选择` ✓ → 引擎 `可选支付` 直接取 ✓。
     *   ⚠ 2026-10：以前这里落进了普通"选"槽 ✗（`归:'选'`），log 里回包**没有 `选`** ✓ → 支付永远失败 ✗。
     */
    if (d.选什么 === '支付源') {
      const 数量 = (d.数量 ?? {}) as { 最小?: number; 最大?: number };
      const 费 = 数量.最小 || 数量.最大 || 1;
      const 候选 = ((d.候选 || []) as { 键: number; 名称: string; 提供?: number }[])
        .map((c) => ({ 键: c.键, 名: c.名称, 提供: c.提供 ?? 1 }));
      return { 标题,
        槽: [支付源槽(候选, 费, 费)],
        确认后发: { 种类: '决定', 接受: true, 选: '$支付源' },
        ...(d.可取消 ? { 放弃后发: { 种类: '决定', 接受: false }, 放弃名: '取消' } : {}) };
    }
    const 呈现: '按钮' | undefined = d.选什么 === '选项' ? '按钮' : undefined;
    const 槽源 = Array.isArray(d.槽) && d.槽.length
      ? (d.槽 as { 名: string; 数量?: unknown; 候选?: unknown[] }[])
      : [{ 名: '选择', 数量: d.数量 ?? { 最小: 1, 最大: 1 }, 候选: d.候选 as unknown[] | undefined }];
    // ⚠ 选「阵地」时，槽的条件看「阵地属于谁的半场」（`阵地玩家`），而不是"谁在选"：
    //   087 调虎离山 是你替**对手**挑他自己那半场的空阵地（以前写成选的人 → 高亮错半场）
    const 槽条件 = d.选什么 === '阵地' && typeof d.阵地玩家 === 'number' ? { 玩家: d.阵地玩家 } : 条件;
    const 槽s: 槽[] = 槽源.map((z) => {
      const 候选2 = 键候选项(z.候选, g);
      return {
        名: z.名, 归: '选', 需: 名额(z.数量, 1), 候选: 候选2, 条件: 槽条件,
        ...(呈现 ? { 呈现 } : {}),
        // ⚠ 过渡标记 `可查看` 已删 ✗（客户端只认 `需求.查看` ✓，留着只会再误导 ✓）
      };
    });
    // ⚠ **有"要看的"或"要选的"任一样，就得发面板** ✗→✓：
    //   开局检视（后手看牌库顶 ✓）**没有候选** ✓（只看不选 ✓）——
    //   原来这里只认候选 ✗ → 它被判成"没东西" → `需求 = null` → **面板整个不存在** ✗
    //   （2026-10 用户报的"现在直接没有开局检视了" ✓ 就是这个 ✓）。
    const 查看 = 查看内容(d, 槽s.flatMap((z) => z.候选), g);      // ← 判定只有一处 ✓
    if (!槽s.length || !(槽s.some((z) => z.候选.length) || 查看.length)) return null;
    return { 标题, 槽: 槽s,
      ...(查看.length ? { 查看 } : {}),
      确认后发: { 种类: '决定', 接受: true, 选: '$选' } };
  }
  return null;
}

